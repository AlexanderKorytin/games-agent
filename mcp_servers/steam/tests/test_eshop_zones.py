def test_европа_бесплатная_игра(зоны, monkeypatch):

    async def цены(к, регион, номера):
        return {ИГРА.номер: Цена(0, 0, 0, "EUR", "")}

    monkeypatch.setattr(es, "цены", цены)
    игра = запуск(eshop.игра(КЛИЕНТ, ГЕРМАНИЯ, "1"))
    assert (игра.цена, игра.бесплатна, игра.валюта) == (0, True, "EUR")


def test_европа_поиск_дозаполняет_цену_одной_пачкой(зоны, monkeypatch):
    # Цена есть только у второй игры выдачи: раскладка по порядку вместо номера попалась бы.
    вызовы = []

    async def цены(к, регион, номера):
        вызовы.append((регион.страна, list(номера)))
        return {ДРУГАЯ.номер: Цена(799, 799, 0, "EUR", "")}

    monkeypatch.setattr(es, "цены", цены)
    игры = запуск(eshop.найти_по_названию(КЛИЕНТ, ГЕРМАНИЯ, "Hollow"))
    assert вызовы == [("DE", [ИГРА.номер, ДРУГАЯ.номер])]
    assert [(и.номер, и.цена, и.валюта, и.скидка_до) for и in игры] == [
        (ИГРА.номер, None, "", ""), (ДРУГАЯ.номер, 799, "EUR", ""),
    ]


