"""Единая точка eShop: каждая функция зовёт модуль зоны своего региона (модули зон подменены),
зона «Европа» дозаполняет цену из общего `цены`, функции Америк европейского региона не получают."""

import asyncio
from dataclasses import replace

import pytest

import eshop
import eshop_eu as eu
import eshop_store as es
from eshop_store import Регион, Цена
import steam_store as ss
from steam_store import Игра

США = es.регион("US")
ГЕРМАНИЯ = es.регион("DE")
КЛИЕНТ = object()

ИГРА = Игра(номер=70010000000001, имя="Hollow Knight", объект="1")
ДРУГАЯ = Игра(номер=70010000000002, имя="Celeste", объект="2")


def запуск(сопрограмма):
    return asyncio.run(сопрограмма)


class Журнал:
    """Подменяет функции зоны модуля: каждая пишет вызов и отдаёт заданный ответ."""

    def __init__(self, monkeypatch, модуль, имя_зоны: str, ответы: dict[str, object]):
        self.вызовы: list[tuple] = []
        for имя, ответ in ответы.items():
            monkeypatch.setattr(модуль, имя, self._подделка(имя_зоны, имя, ответ))

    def _подделка(self, зона, имя, ответ):
        async def подделка(к, регион, *доводы, **именные):
            assert к is КЛИЕНТ
            self.вызовы.append((зона, имя, регион.страна, доводы, tuple(sorted(именные.items()))))
            return ответ
        return подделка


ФУНКЦИИ = ("витрина", "найти_по_названию", "игра", "найти_в_eshop")


@pytest.fixture
def зоны(monkeypatch):
    журнал: list = []
    америки = Журнал(monkeypatch, es, "америки", {
        "витрина": [ИГРА], "найти_по_названию": [ИГРА], "игра": ИГРА, "найти_в_eshop": ИГРА,
    })
    европа = Журнал(monkeypatch, eu, "европа", {
        "витрина": [ИГРА], "найти_по_названию": [ИГРА, ДРУГАЯ], "игра": ИГРА, "найти_в_eshop": ИГРА,
    })
    америки.вызовы = европа.вызовы = журнал
    цены_вызовы: list = []

    async def цены(к, регион, номера):
        assert к is КЛИЕНТ
        цены_вызовы.append((регион.страна, list(номера)))
        return {ИГРА.номер: Цена(1499, 2999, 50, "EUR", "2026-10-31")}

    monkeypatch.setattr(es, "цены", цены)
    return журнал, цены_вызовы


def вызвать(имя: str, регион: Регион):
    if имя == "витрина":
        return eshop.витрина(КЛИЕНТ, регион, будущие=True, страница=3)
    if имя == "найти_по_названию":
        return eshop.найти_по_названию(КЛИЕНТ, регион, "Hollow")
    if имя == "игра":
        return eshop.игра(КЛИЕНТ, регион, "1")
    return eshop.найти_в_eshop(КЛИЕНТ, регион, ИГРА)


@pytest.mark.parametrize("имя", ФУНКЦИИ)
def test_америки_зовут_eshop_store(зоны, имя):
    журнал, цены_вызовы = зоны
    запуск(вызвать(имя, США))
    assert [(з, и, с) for з, и, с, *_ in журнал] == [("америки", имя, "US")]
    # Цена Америк — в записи индекса: общий `цены` не зовётся.
    assert цены_вызовы == []


@pytest.mark.parametrize("имя", ФУНКЦИИ)
def test_европа_зовёт_eshop_eu(зоны, имя):
    журнал, _ = зоны
    запуск(вызвать(имя, ГЕРМАНИЯ))
    assert [(з, и, с) for з, и, с, *_ in журнал] == [("европа", имя, "DE")]


def test_доводы_доходят_до_зоны(зоны):
    журнал, _ = зоны
    запуск(eshop.витрина(КЛИЕНТ, ГЕРМАНИЯ, будущие=False, страница=7))
    запуск(eshop.найти_по_названию(КЛИЕНТ, США, "Celeste"))
    запуск(eshop.игра(КЛИЕНТ, ГЕРМАНИЯ, "1125772"))
    запуск(eshop.найти_в_eshop(КЛИЕНТ, США, ДРУГАЯ))
    assert [(и, д, им) for _, и, _, д, им in журнал] == [
        ("витрина", (), (("будущие", False), ("страница", 7))),
        ("найти_по_названию", ("Celeste",), ()),
        ("игра", ("1125772",), ()),
        ("найти_в_eshop", (ДРУГАЯ,), ()),
    ]


@pytest.mark.parametrize("регион", [Регион("JP", "азия", "x"), Регион("DE", "Европа", "de")])
@pytest.mark.parametrize("имя", ФУНКЦИИ)
def test_чужая_зона_ошибка(зоны, имя, регион):
    журнал, _ = зоны
    with pytest.raises(ValueError, match="зона"):
        запуск(вызвать(имя, регион))
    assert журнал == []


def test_европа_игра_дозаполняет_цену(зоны):
    _, цены_вызовы = зоны
    игра = запуск(eshop.игра(КЛИЕНТ, ГЕРМАНИЯ, "1"))
    assert цены_вызовы == [("DE", [ИГРА.номер])]
    assert игра == replace(ИГРА, цена=1499, цена_без_скидки=2999, скидка=50, валюта="EUR",
                           скидка_до="2026-10-31")


def test_европа_игра_без_продажи_цена_пуста(зоны, monkeypatch):
    _, цены_вызовы = зоны
    Журнал(monkeypatch, eu, "европа", {"игра": ДРУГАЯ})
    игра = запуск(eshop.игра(КЛИЕНТ, ГЕРМАНИЯ, "2"))
    assert цены_вызовы == [("DE", [ДРУГАЯ.номер])]
    assert игра == ДРУГАЯ
    assert (игра.цена, игра.цена_без_скидки, игра.скидка, игра.валюта, игра.скидка_до) == (None, None, 0, "", "")


