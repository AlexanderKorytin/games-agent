def test_найти_в_steam_общий(monkeypatch):
    вызовы = []

    async def найти(к_steam, игра, *, страна_steam):
        вызовы.append((к_steam, игра, страна_steam))
        return 367520

    monkeypatch.setattr(es, "найти_в_steam", найти)
    assert запуск(eshop.найти_в_steam(КЛИЕНТ, ИГРА, страна_steam="KZ")) == 367520
    assert вызовы == [(КЛИЕНТ, ИГРА, "KZ")]


