"""Nintendo eShop: единая точка зон. Задания и сервер зовут её и не знают, какая зона у страны.

Функции каталога (`витрина`, `найти_по_названию`, `игра`, `найти_в_eshop`) выбирают модуль по
`регион.зона`: «америки» — `eshop_store`, «европа» — `eshop_eu`. Иная зона — `ValueError`:
функции Америк европейский регион не получают и наоборот (молча ушли бы не в тот каталог).
Модуль зоны берётся в миг вызова, не при загрузке: проверки подменяют его функции.

Общее для зон — из `eshop_store`: `цены` (`api.ec` по стране), `найти_в_steam`, `регион`,
`СТРАНЫ`, `клиент`.

Цена. У Америк она в записи индекса. В записи Европы цены нет: `игра` и `найти_по_названию`
дозаполняют её одной пачкой `цены` на все номера ответа (`цена`, `цена_без_скидки`, `скидка`,
`валюта`, `скидка_до`; цена 0 — `бесплатна`, как у Америк). Нет в продаже — поля пусты. Сбой
`цены` (`ОшибкаМагазина`) запись не роняет: каталог ответил, игра отдаётся без цены — её подтянет
задание дня, а ошибка цены не должна прятать найденную игру.
`витрина` и `найти_в_eshop` цену не дозаполняют: кандидатов витрины много, до суда цена не нужна,
а пара eShop ↔ Steam ищется ради номера; цену такой игры задания берут `цены` своим ходом.

Состояния у модуля нет, на диск он не пишет.
"""

from __future__ import annotations

import dataclasses
from types import ModuleType

import httpx2

import eshop_eu
import eshop_store
import steam_store as ss
from eshop_store import СТРАНЫ, Регион, Цена, клиент, регион
from steam_store import Игра

__all__ = ["СТРАНЫ", "Регион", "Цена", "витрина", "игра", "клиент", "найти_в_eshop",
           "найти_в_steam", "найти_по_названию", "регион", "цены"]

_ЗОНЫ: dict[str, ModuleType] = {"америки": eshop_store, "европа": eshop_eu}


def _зона(регион: Регион) -> ModuleType:
    модуль = _ЗОНЫ.get(регион.зона)
    if модуль is None:
        raise ValueError(f"зона eShop «{регион.зона}» страны {регион.страна} не поддержана")
    return модуль


async def _с_ценами(к: httpx2.AsyncClient, регион: Регион, игры: list[Игра]) -> list[Игра]:
    """Игры Европы с ценой страны: одна пачка `цены` на все номера. Сбой `цены` — игры без цены."""
    if not игры:
        return игры
    try:
        найдено = await eshop_store.цены(к, регион, [и.номер for и in игры])
    except ss.ОшибкаМагазина:
        # Каталог ответил, `api.ec` нет: запись без цены полезнее ошибки, цену подтянет задание дня.
        return игры
    итог = []
    for и in игры:
        ц = найдено.get(и.номер)
        if ц is not None:
            и = dataclasses.replace(и, цена=ц.цена, цена_без_скидки=ц.цена_без_скидки, скидка=ц.скидка,
                                    валюта=ц.валюта, скидка_до=ц.до, бесплатна=ц.цена == 0)
        итог.append(и)
    return итог


async def витрина(к: httpx2.AsyncClient, регион: Регион, *, будущие: bool, страница: int) -> list[Игра]:
    """Одна страница каталога страны. Цена Европы не дозаполняется (шапка)."""
    return await _зона(регион).витрина(к, регион, будущие=будущие, страница=страница)


async def найти_по_названию(к: httpx2.AsyncClient, регион: Регион, название: str) -> list[Игра]:
    """Поиск каталога страны по названию; у Европы — с ценой страны."""
    модуль = _зона(регион)
    игры = await модуль.найти_по_названию(к, регион, название)
    return await _с_ценами(к, регион, игры) if модуль is eshop_eu else игры


async def игра(к: httpx2.AsyncClient, регион: Регион, объект: str) -> Игра | None:
    """Запись каталога страны с полным описанием; у Европы — с ценой страны."""
    модуль = _зона(регион)
    найдена = await модуль.игра(к, регион, объект)
    if найдена is None or модуль is not eshop_eu:
        return найдена
    return (await _с_ценами(к, регион, [найдена]))[0]


async def найти_в_eshop(к: httpx2.AsyncClient, регион: Регион, игра: Игра) -> Игра | None:
    """Та же игра в eShop страны — точное совпадение имён. Цена не дозаполняется (шапка)."""
    return await _зона(регион).найти_в_eshop(к, регион, игра)


async def цены(к: httpx2.AsyncClient, регион: Регион, номера: list[int]) -> dict[int, Цена]:
    """Цены страны из `api.ec` — общие для зон."""
    _зона(регион)
    return await eshop_store.цены(к, регион, номера)


async def найти_в_steam(к_steam: httpx2.AsyncClient, игра: Игра, *, страна_steam: str) -> int | None:
    """Номер той же игры в Steam страны `страна_steam` — общий для зон."""
    return await eshop_store.найти_в_steam(к_steam, игра, страна_steam=страна_steam)
