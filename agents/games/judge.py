"""Отбор игры местной моделью: «подходит» или «не подходит» и причина одной фразой.

Ход задания ведёт программа, а модель только судит одну игру за запрос. Причина — замер дня
31: местная модель зовёт инструменты не каждый раз, а пропущенный вызов в задании без человека
— тихая потеря недели. Ответ — по схеме JSON (`response_format` профиля `отбор-игр`), поэтому
числового порога нет: модель отвечает словом.

Агент — `Agent` `myharness` без хранилища разговора: каждая игра судится с чистого листа, и
вердикт по одной игре не влияет на следующую. Обмен пишется в журнал прогонов `myharness`.

Суд пачкой (`судить_пачкой`, седьмой заход Research в `docs/игровой-агент.md`): модель получает
5 номеров и сама берёт сведения инструментами MCP `steam_game` и `eshop_game` по пошаговой
инструкции профиля `отбор-игр-mcp`. Ответ программа не принимает на веру: JSON-список, каждый
номер пачки ровно один раз, и по каждому номеру в звеньях обмена есть удачный вызов нужного
инструмента. `response_format` здесь нет: с ним Ollama не даёт модели звать инструменты (проба
2026-10-19 на `qwen3.5:9b-q4_K_M-32k`: 3 из 3 ответов — сразу JSON без вызова).
"""

