class НетИнструментов(RuntimeError):
    """Суду пачкой нечем судить: инструменты MCP не поднялись или профиль пачки не загружен.
    Повтор и следующие пачки запуска упрутся в то же — задание судит по одной до конца запуска."""


@dataclass(frozen=True)
class Вердикт:
    подходит: bool
    причина: str


def профиль(имя: str = ПРОФИЛЬ) -> profiles.Profile:
    найден, предупреждения = profiles.load(имя)
    if найден.source is None:
        raise RuntimeError(f"профиль {имя} не загружен: {'; '.join(предупреждения)}")
    return найден


def _инварианты(каталог: Path, профиль_отбора: profiles.Profile) -> str:
    """Блок «Инварианты» для запроса отбора. Запреты игр («Не предлагать: …») программа уже
    отсеяла до суда; в запросе они только росли бы с каждым минусом и через сотню минусов
    вытеснили бы окно местной модели (просмотр шва)."""
    список, _ = invariants.собрать(каталог, None, профиль_отбора)
    return invariants.блок([и for и in список if not taste.номер_запрета(и.текст)])


def запрос(каталог: Path, игра: Игра, профиль_отбора: profiles.Profile, похожие: str = "") -> str:
    """Текст запроса: вкус, инварианты папки, игра. Инварианты идут здесь же, а не только
    фильтром программы: модель должна знать, почему отвергнуты похожие игры."""
    блок = _инварианты(каталог, профиль_отбора)
    жанры = ", ".join(игра.жанры) or "не указаны"
    # Оценка игры eShop — оценка игроков Metacritic в тех же полях `отзывы`: модель не должна
    # видеть «Оценка пользователей Steam» у игры Switch.
    if это_eshop(игра.номер):
        магазин, оценка = "Nintendo eShop", "Оценка игроков Metacritic"
    else:
        магазин, оценка = "Steam", "Оценка пользователей Steam"
    части = [
        "## Вкус человека",
        taste.вкус(каталог) or "(вкус не записан)",
    ]
    if блок:
        части += ["", блок]
    if похожие:
        # RAG: решения человека по похожим играм — точнее обобщённого вкуса.
        части += ["", похожие]
    части += [
        "",
        "## Игра",
        f"Название: {игра.имя}",
        f"Магазин: {магазин}",
        f"Жанры: {жанры}",
        f"Выход: {игра.дата_текст or 'не объявлен'}",
        f"{оценка}: {игра.отзывы.текст()}",
        f"Описание: {игра.описание or 'нет'}",
    ]
    return "\n".join(части)


def разобрать(текст: str) -> Вердикт:
    """Вердикт из ответа. Не разобрался — `ValueError` с текстом ответа: задание пишет его в
    ленту, а не принимает молчание за «не подходит»."""
    try:
        данные = json.loads(текст)
    except json.JSONDecodeError:
        raise ValueError(f"ответ модели — не JSON: {текст[:300]!r}") from None
    if not isinstance(данные, dict) or not isinstance(данные.get("подходит"), bool):
        raise ValueError(f"в ответе модели нет поля «подходит»: {текст[:300]!r}")
    return Вердикт(данные["подходит"], " ".join(str(данные.get("причина") or "").split()))


async def судить(клиент: api.Clients, каталог: Path, игра: Игра, похожие: str = "") -> Вердикт:
    профиль_отбора = профиль()
    агент = Agent(ПРОФИЛЬ, профиль_отбора)
    ход = await агент.exchange(клиент, модель(), запрос(каталог, игра, профиль_отбора, похожие))
    if not ход.ok:
        raise RuntimeError(f"местная модель не ответила: {ход.error or ход.status}")
    return разобрать(ход.text)


