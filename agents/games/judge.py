def _магазин(игра: Игра) -> tuple[str, str]:
    """Подпись магазина и инструмент сведений игры."""
    return ("Nintendo eShop", ESHOP_GAME) if это_eshop(игра.номер) else ("Steam", STEAM_GAME)


def запрос_пачки(
    каталог: Path, игры: list[Игра], похожие: dict[int, str], профиль_отбора: profiles.Profile
) -> str:
    """Вкус, инварианты и пачка (номер, магазин, имя, похожие из истории). Шаги и формат ответа —
    в профиле `отбор-игр-mcp`, в одном месте. Сведений об игре в запросе нет: их модель берёт
    инструментом — для этого суд и идёт через MCP."""
    части = ["## Вкус человека", taste.вкус(каталог) or "(вкус не записан)"]
    if блок := _инварианты(каталог, профиль_отбора):
        части += ["", блок]
    части += ["", "## Пачка игр"]
    for игра in игры:
        магазин, _ = _магазин(игра)
        части.append(f"- {игра.номер} — {магазин} — {игра.имя}")
        # Блок `similar.блок` несёт свой заголовок раздела; внутри пачки он лишний.
        строки = [с for с in (похожие.get(игра.номер) or "").splitlines() if с.strip() and not с.startswith("#")]
        if строки:
            части.append("  Похожие игры из истории человека:")
            части += [f"  {с.strip()}" for с in строки]
    return "\n".join(части)


def _кратко(текст: str) -> str:
    return repr(текст[:300])


def _номер(значение: object) -> int | None:
    """Номер из ответа или доводов: целое JSON либо строка из одних цифр. Дробь и научная запись
    (`1.97e+06`, `1970000.0`) — не номер: цифры номера в них уже потеряны."""
    if isinstance(значение, bool):
        return None
    if isinstance(значение, int):
        return значение
    if isinstance(значение, str) and значение.strip().isdigit():
        return int(значение.strip())
    return None


def _пункты_без_скобок(очищено: str, текст: str) -> list:
    """Пункты без `[ ]` — построчно или через запятую (живой прогон 2026-10-19: модель отдала
    верные пункты построчно). Между пунктами — только пробелы и запятые; иначе «не JSON»."""
    разбор, пункты, i = json.JSONDecoder(), [], 0
    очищено = очищено.strip()
    while i < len(очищено):
        if очищено[i] in " \t\r\n,":
            i += 1
            continue
        try:
            пункт, i = разбор.raw_decode(очищено, i)
        except json.JSONDecodeError:
            raise ValueError(f"ответ модели — не JSON: {_кратко(текст)}") from None
        if not isinstance(пункт, dict):
            raise ValueError(f"ответ модели — не JSON-список: {_кратко(текст)}")
        пункты.append(пункт)
    if not пункты:
        raise ValueError(f"ответ модели — не JSON: {_кратко(текст)}")
    return пункты


def _вырезать_список(текст: str) -> list:
    """JSON-список из ответа: модель может обернуть его в ```json и пару слов вокруг либо отдать
    пункты без скобок списка."""
    очищено = re.sub(r"```(?:json)?", "", текст)
    начало, конец = очищено.find("["), очищено.rfind("]")
    if начало < 0 or конец < начало:
        return _пункты_без_скобок(очищено, текст)
    try:
        данные = json.loads(очищено[начало : конец + 1])
    except json.JSONDecodeError:
        raise ValueError(f"ответ модели — не JSON: {_кратко(текст)}") from None
    if not isinstance(данные, list):
        raise ValueError(f"ответ модели — не JSON-список: {_кратко(текст)}")
    return данные


def _спрошены(звенья: list[dict]) -> set[tuple[str, int]]:
    """Пары (инструмент, номер) удачных вызовов обмена. Вызов, на который инструмент ответил
    ошибкой, сведений модели не дал и не считается."""
    результаты = {
        з.get("tool_call_id"): str(з.get("content") or "") for з in звенья if з.get("role") == "tool"
    }
    спрошены: set[tuple[str, int]] = set()
    for звено in звенья:
        if звено.get("role") != "assistant":
            continue
        for вызов in звено.get("tool_calls") or ():
            функция = вызов.get("function") or {}
            имя = функция.get("name", "")
            if имя not in ДОВОДЫ:
                continue
            результат = результаты.get(вызов.get("id"))
            if результат is None or результат.startswith("ошибка инструмента"):
                continue
            try:
                доводы = json.loads(функция.get("arguments") or "{}")
            except json.JSONDecodeError:
                continue
            номер = _номер(доводы.get(ДОВОДЫ[имя])) if isinstance(доводы, dict) else None
            if номер is not None:
                спрошены.add((имя, номер))
    return спрошены


def разобрать_пачку(текст: str, игры: list[Игра], звенья: list[dict]) -> dict[int, Вердикт]:
    """Вердикты пачки. Ответ принимается целиком или не принимается: каждый номер пачки ровно
    один раз, чужих нет, `подходит` — bool, причина не пуста, и по каждому номеру был удачный вызов инструмента его
    магазина. Иначе `ValueError` с причиной — задание повторит пачку или судит её прежним путём."""
    пункты = _вырезать_список(текст)
    пачка = {игра.номер: игра for игра in игры}
    вердикты: dict[int, Вердикт] = {}
    for пункт in пункты:
        if not isinstance(пункт, dict):
            raise ValueError(f"пункт ответа — не объект: {_кратко(json.dumps(пункт, ensure_ascii=False))}")
        номер = _номер(пункт.get("номер"))
        if номер is None:
            raise ValueError(f"номер {пункт.get('номер')!r} не целое: {_кратко(текст)}")
        if номер not in пачка:
            raise ValueError(f"номер {номер} не из пачки: {_кратко(текст)}")
        if номер in вердикты:
            raise ValueError(f"номер {номер} в ответе дважды: {_кратко(текст)}")
        if not isinstance(пункт.get("подходит"), bool):
            raise ValueError(f"у номера {номер} поле «подходит» не true/false: {_кратко(текст)}")
        # Причину читает человек: пустая — ответ не принят, пачка уйдёт на повтор.
        if not (причина := " ".join(str(пункт.get("причина") or "").split())):
            raise ValueError(f"нет причины у номера {номер}: {_кратко(текст)}")
        вердикты[номер] = Вердикт(пункт["подходит"], причина)
    if пропущены := [н for н in пачка if н not in вердикты]:
        raise ValueError(f"нет ответа по номерам {', '.join(map(str, пропущены))}: {_кратко(текст)}")
    спрошены = _спрошены(звенья)
    for номер, игра in пачка.items():
        _, инструмент = _магазин(игра)
        if (инструмент, номер) not in спрошены:
            raise ValueError(
                f"по номеру {номер} не было удачного вызова {инструмент}"
            )
    return вердикты


def _записать(путь: Path, текст: str) -> None:
    """Файл каталога суда: только при изменении и одним движением (черновик рядом, `replace`) —
    общие `Соединения` читают `.mcp.json` и разрешения перед каждым обменом и на каждый вызов,
    и полузаписанный файл не должен попасть им в руки."""
    try:
        if путь.read_text("utf-8") == текст:
            return
    except FileNotFoundError:
        pass
    черновик = путь.with_name(f".{путь.name}.{os.getpid()}.tmp")
    черновик.write_text(текст, "utf-8")
    черновик.replace(путь)


def подготовить_каталог_инструментов(каталог: Path) -> Path:
    """Каталог набора суда: сервер `steam` тот же, что у советника (`advisor.подготовить_каталог`)
    — запись совпадает, и общие `Соединения` держат один процесс сервера, — а разрешены только
    два инструмента сведений. Пишется при каждом суде заново: путь к серверу следует за кодом."""
    from advisor import СЕРВЕР

    свой = каталог / КАТАЛОГ_ИНСТРУМЕНТОВ
    (свой / ".claude").mkdir(parents=True, exist_ok=True)
    mcp = {
        "mcpServers": {
            "steam": {
                "type": "stdio",
                "command": "uv",
                "args": ["run", "--project", str(СЕРВЕР), str(СЕРВЕР / "server.py")],
                "env": {"GAMES_DATA_DIR": str(каталог)},
            }
        }
    }
    _записать(свой / ".mcp.json", json.dumps(mcp, ensure_ascii=False, indent=1))
    _записать(
        свой / ".claude" / "settings.json",
        json.dumps({"permissions": {"allow": list(ДОВОДЫ)}}, ensure_ascii=False, indent=1),
    )
    return свой


def _сузить(набор: Инструменты | None, нужны: set[str]) -> Инструменты:
    """Только `steam_game` и `eshop_game`, даже если набор принёс больше. Нет нужного пачке —
    `RuntimeError` с жалобой набора: без инструмента модель судила бы вслепую."""
    схемы = [с for с in (набор.схемы if набор else []) if (с.get("function") or {}).get("name") in ДОВОДЫ]
    есть = {с["function"]["name"] for с in схемы}
    if недостаёт := sorted(нужны - есть):
        жалоба = набор.жалоба if набор and набор.жалоба else "сервер не отдал инструмент"
        raise НетИнструментов(f"инструменты MCP для суда пачкой не получены ({', '.join(недостаёт)}): {жалоба}")
    исполнить = набор.исполнить

    async def только_свои(имя: str, доводы: str) -> str:
        if имя not in есть:
            raise PermissionError(f"инструмент {имя} не разрешён")
        return await исполнить(имя, доводы)

    return Инструменты(схемы, только_свои, жалоба=набор.жалоба)


async def судить_пачкой(
    клиент: api.Clients,
    каталог: Path,
    игры: list[Игра],
    похожие: dict[int, str],
    *,
    соединения: Соединения | None = None,
) -> dict[int, Вердикт]:
    """Суд пачки одним обменом: модель сама берёт сведения инструментами MCP и отвечает
    JSON-списком. Ответ не прошёл проверку или обмен не уложился в `СРОК_ПАЧКИ_С` — `ValueError`
    (задание повторит пачку или уведёт её на запасной путь); обмен не удался
    или инструменты не поднялись — `RuntimeError`, а нечем судить (инструменты, профиль) — `НетИнструментов`. Свои `Соединения` закрываются здесь же,
    переданные — остаются вызывающему."""
    if not игры:
        return {}
    свои = соединения is None
    соединения = Соединения() if свои else соединения
    try:
        набор = _сузить(
            await соединения.набор(подготовить_каталог_инструментов(каталог)),
            {_магазин(игра)[1] for игра in игры},
        )
        try:
            профиль_отбора = профиль(ПРОФИЛЬ_ПАЧКИ)
        except RuntimeError as exc:
            raise НетИнструментов(str(exc)) from None
        имя_модели = await модель_пачки()
        агент = Agent(ПРОФИЛЬ_ПАЧКИ, профиль_отбора, инструменты=lambda: набор)
        текст = запрос_пачки(каталог, игры, похожие, профиль_отбора)
        срок = СРОК_ПАЧКИ_С
        try:
            async with asyncio.timeout(срок) as рамка:
                ход = await агент.exchange(клиент, имя_модели, текст)
        except TimeoutError:
            if not рамка.expired():
                raise
            raise ValueError(f"пачка не уложилась в {срок:g} с") from None
        # Обмен мог сам поймать отмену и вернуть итог «отменён»: истёк срок — та же причина.
        if рамка.expired():
            raise ValueError(f"пачка не уложилась в {срок:g} с")
    finally:
        if свои:
            await соединения.закрыть()
    if not ход.ok:
        raise RuntimeError(f"местная модель не ответила: {ход.error or ход.status}")
    return разобрать_пачку(ход.text, игры, ход.звенья)
