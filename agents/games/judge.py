def модель() -> str:
    """Модель отбора — выбранная в мастере сборка (`models`), окно службы по умолчанию: запросу
    отбора (~1,5 тыс. токенов) большое окно не нужно. Переопределяется окружением."""
    if свою := os.environ.get("GAMES_LOCAL_MODEL"):
        return свою
    import games_db
    import models

    с = games_db.открыть()
    try:
        return "ollama/" + models.выбрана(с)
    finally:
        с.close()


