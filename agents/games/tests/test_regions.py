# Номера eShop — nsuid от `7001…` (`eshop_store.это_eshop`).
E1, E2, E3 = 70010000000001, 70010000000002, 70010000000003
N1, N2 = 70010000000101, 70010000000102  # те же игры в новой зоне
SWITCH, SWITCH_2 = "Nintendo Switch", "Nintendo Switch 2"


def игра(номер, имя=None, *, цена=100000, валюта="RUB", отзывы=None, объект="", платформы=()):
    return ss.Игра(номер=номер, имя=имя or f"игра {номер}", цена=цена, цена_без_скидки=цена,
                   валюта=валюта, отзывы=отзывы or ss.НЕТ_ОТЗЫВОВ, объект=объект,
                   платформы=платформы)


def нельзя(*_):
    raise AssertionError("эта ветвь не должна звать магазин")


def асинх(функция):
    async def обёртка(*доводы):
        return функция(*доводы)
    return обёртка


def магазины(**поля) -> regions.Магазины:
    return regions.Магазины(**{имя: асинх(ф) for имя, ф in поля.items()})


def пересобрать(с, магазины_, **доводы) -> regions.Итог:
    доводы.setdefault("страны", {"steam": "KZ", "eshop": "US"})
    return asyncio.run(regions.пересобрать(с, магазины_, **доводы))


def хранилище():
    return games_db.открыть()


def строки(с, таблица):
    return {с_[0] for с_ in с.execute(f"SELECT номер FROM {таблица}").fetchall()}


def последний_итог(с) -> str:
    return games_db.лента(с, 1)[0]["текст"]


# ---- Steam ----


def test_steam_игры_нет_в_стране_удалена_другая_обновлена():
    с = хранилище()
    games_db.запомнить_игру(с, игра(10, "Ушедшая"))
    games_db.оценить(с, 10, True, "нравится")
    games_db.запомнить_игру(с, игра(20, "Оставшаяся", отзывы=ss.Отзывы("Очень положительные", 90, 100)))
    games_db.в_календарь(с, 20, "ждём")
    games_db.отметить_цену(с, 20, 100000, 0, валюта="RUB")
    взяты: list[int] = []

    def игра_steam(номер):
        взяты.append(номер)
        return None if номер == 10 else игра(20, "Оставшаяся", цена=410000, валюта="KZT")

    итог = пересобрать(с, магазины(игра_steam=игра_steam), steam_сменилась=True, eshop="без_изменений")

    assert взяты == [10, 20]
    assert games_db.игра(с, 10) is None and 10 not in строки(с, "suggestions")
    запись = games_db.игра(с, 20)
    assert (запись["цена"], запись["валюта"]) == (410000, "KZT")
    assert запись["отзывы_всего"] == 100  # сводка без отзывов не стирает прежнюю
    assert 20 in строки(с, "calendar")
    assert строки(с, "prices") == set() and строки(с, "price_history") == set()
    assert (итог.обновлено, итог.удалено, итог.не_проверено) == (["Оставшаяся"], ["Ушедшая"], [])
    assert последний_итог(с) == "Регион сменён: обновлено 1, удалено 1 (Ушедшая), не проверено 0"
    assert games_db.лента(с, 1)[0]["род"] == "итог"


