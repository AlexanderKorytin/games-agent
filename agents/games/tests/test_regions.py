def test_steam_список_желаемого_steam_берётся_заново_и_не_удаляется():
    с = хранилище()
    games_db.запомнить_игру(с, игра(70, "Из списка"))
    games_db.запомнить_игру(с, игра(80, "Нет в Казахстане"))
    games_db.обновить_список_steam(с, [70, 80, 90])  # у 90 карточки нет
    взяты: list[int] = []

    def игра_steam(номер):
        взяты.append(номер)
        return игра(70, "Из списка", цена=410000, валюта="KZT") if номер == 70 else None

    итог = пересобрать(с, магазины(игра_steam=игра_steam), steam_сменилась=True,
                       eshop="без_изменений")

    assert sorted(взяты) == [70, 80, 90]
    assert (games_db.игра(с, 70)["цена"], games_db.игра(с, 70)["валюта"]) == (410000, "KZT")
    assert games_db.игра(с, 80) is not None  # список ведёт Steam — карточка остаётся
    запись = games_db.игра(с, 80)  # цена прежней страны стёрта
    assert (запись["цена"], запись["цена_без_скидки"], запись["скидка"], запись["валюта"],
            запись["скидка_до"]) == (None, None, 0, "", None)
    assert games_db.список_steam(с) == {70, 80, 90}
    assert итог.удалено == [] and итог.обновлено == ["Из списка"]
    assert sorted(итог.нет_в_регионе) == ["Нет в Казахстане", "№90"]
    assert последний_итог(с) == (
        "Регион сменён: обновлено 1, удалено 0, не проверено 0; "
        "в списке желаемого Steam нет в регионе: 2 (Нет в Казахстане, №90)"
    )


