def _снимок(с) -> dict:
    return {
        т: sorted(tuple(р) for р in с.execute(f"SELECT * FROM {т}").fetchall())
        for т in ("games", "suggestions", "calendar", "played", "prices", "price_history",
                  "pairs", "marks", "feed")
    }


def _хранилище_для_обрыва():
    с = хранилище()
    games_db.задать_страны(с, steam="RU", eshop="DE")
    games_db.запомнить_игру(с, игра(10, "Ушедшая"))
