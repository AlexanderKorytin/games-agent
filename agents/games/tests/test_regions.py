def test_eshop_другая_зона_номер_заменён_ненайденная_удалена_пары_заново():
    с = хранилище()
    games_db.запомнить_игру(с, игра(E1, "Hollow Knight™", объект="hk"))
    games_db.оценить(с, E1, True, "метроидвания")
    games_db.запомнить_игру(с, игра(E2, "Europe Only", объект="eu"))
    games_db.в_календарь(с, E2, "ждём")
    games_db.отметить_цену(с, E1, 100000, 0, валюта="EUR")
    # Игры Steam: с найденной парой и с «искали, не нашли».
    games_db.запомнить_игру(с, игра(40, "Celeste"))
    games_db.предложить(с, 40, "причина")
    games_db.записать_пару(с, 40, E1)
    games_db.запомнить_игру(с, игра(50, "Hades"))
    games_db.предложить(с, 50, "причина")
    games_db.записать_пару(с, 50, None)
    games_db.отметить_цену(с, 50, 100000, 0, валюта="RUB")
    # Пара игры вне работы (только в списке желаемого Steam) — тоже данные прежней зоны.
    games_db.записать_пару(с, 60, E3)

    прежние = {"hk": игра(E1, "Hollow Knight", объект="hk", платформы=(SWITCH,)), "eu": None}
    искали: list[str] = []

    def найти(название):
        искали.append(название)
        if название == "Hollow Knight":
            return [
                игра(N2, "Hollow Knight – Nintendo Switch 2 Edition", цена=1499, валюта="USD",
                     платформы=(SWITCH_2,)),
                игра(N1, "HOLLOW KNIGHT", цена=1499, валюта="USD", объект="hk-us", платформы=(SWITCH,)),
            ]
        return [игра(N2 + 5, "Europe Only 2", платформы=(SWITCH,))]

    пары_искали: list[int] = []
    PAIR = 70010000000777

    def пара_eshop(игра_steam):
        пары_искали.append(игра_steam.номер)
        return игра(PAIR, "Hades", цена=2499, валюта="USD") if игра_steam.номер == 50 else None

    итог = пересобрать(
        с,
        магазины(игра_steam=нельзя, найти_eshop=найти, прежняя_eshop=lambda о: прежние[о],
                 пара_eshop=пара_eshop, игра_eshop=нельзя),
        steam_сменилась=False, eshop="другая_зона",
    )

    assert искали == ["Hollow Knight", "Europe Only"]
    # Найдена по точному имени и той же платформе: новый номер, оценка и причина сохранены.
    assert games_db.игра(с, E1) is None
    строка = с.execute(
        "SELECT оценка, причина_оценки FROM suggestions WHERE номер = ?", (N1,)
    ).fetchone()
    assert tuple(строка) == (1, "метроидвания")
    assert [и["номер"] for и in games_db.желаемое(с)] == [N1]
    assert games_db.игра(с, N1)["валюта"] == "USD"
    assert games_db.игра(с, N2) is None  # издание Switch 2 — другая платформа
    # Не найдена — удалена.
    assert games_db.игра(с, E2) is None and E2 not in строки(с, "calendar")
    # Цены eShop сброшены, Steam — нет.
    assert строки(с, "prices") == {50}
    # Пары: все прежние сброшены, у игр Steam найдены заново.
    assert sorted(пары_искали) == [40, 50]
    assert games_db.пара(с, 40) is None and games_db.пара_сверена(с, 40)
    assert games_db.пара(с, 50) == PAIR and games_db.пара(с, PAIR) == 50
    assert not games_db.пара_сверена(с, 60) and not games_db.пара_сверена(с, E3)
    assert games_db.игра(с, PAIR)["валюта"] == "USD"
    assert (итог.обновлено, итог.удалено) == (["Hollow Knight™"], ["Europe Only"])
    assert последний_итог(с) == (
        "Регион сменён: обновлено 1, удалено 1 (Europe Only), не проверено 0"
    )


