def test_eshop_та_же_зона_запись_заново_нет_в_каталоге_удалена():
    с = хранилище()
    for номер, имя in ((E1, "В продаже"), (E2, "Пропавшая"), (E3, "Скоро выйдет")):
        games_db.запомнить_игру(с, игра(номер, имя, объект=f"о{номер}", валюта="USD"))
        games_db.предложить(с, номер, "причина")
        games_db.отметить_цену(с, номер, 100000, 0, валюта="USD")
    games_db.запомнить_игру(с, игра(30, "Steam"))
    games_db.предложить(с, 30, "причина")
    games_db.отметить_цену(с, 30, 100000, 0, валюта="RUB")
    games_db.записать_пару(с, 30, E1)
    записи = {
        f"о{E1}": replace(игра(E1, "В продаже", цена=5999, валюта="CAD", объект=f"о{E1}"),
                         адрес="https://www.nintendo.com/en-ca/store/products/v-prodazhe",
                         описание="Описание Канады"),
        # Не вышедшая игра цены не имеет, но в каталоге страны есть — остаётся.
        f"о{E3}": игра(E3, "Скоро выйдет", цена=None, валюта="", объект=f"о{E3}"),
    }

    итог = пересобрать(
        с,
        магазины(игра_steam=нельзя, игра_eshop=lambda о: записи.get(о), найти_eshop=нельзя,
                 пара_eshop=нельзя),
        steam_сменилась=False, eshop="та_же_зона",
    )

    запись = games_db.игра(с, E1)
    assert (запись["цена"], запись["валюта"], запись["адрес"], запись["описание"]) == (
        5999, "CAD", "https://www.nintendo.com/en-ca/store/products/v-prodazhe", "Описание Канады")
    # Нет в каталоге страны (у цен — `not_found`) — удалена.
    assert games_db.игра(с, E2) is None and E2 not in строки(с, "suggestions")
    assert games_db.игра(с, E3) is not None and E3 in строки(с, "suggestions")
    assert строки(с, "prices") == {30}  # цены eShop сброшены, Steam — целы
    assert games_db.пара(с, 30) == E1  # номера той же зоны прежние — пары верны
    assert sorted(итог.обновлено) == ["В продаже", "Скоро выйдет"]
    assert итог.удалено == ["Пропавшая"]


