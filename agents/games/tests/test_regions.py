def test_eshop_та_же_зона_запись_без_цены_не_затирает_цену_той_же_валюты():
    # Европа DE → FR: валюта та же, запись пришла без цены — прежняя цена остаётся.
    с = хранилище()
    games_db.запомнить_игру(с, replace(игра(E1, "Без цены", цена=1999, валюта="EUR", объект="о1"),
                                       скидка=20, цена_без_скидки=2499, скидка_до="2026-11-01"))
    games_db.предложить(с, E1, "причина")
    games_db.запомнить_игру(с, игра(E2, "С ценой", цена=2999, валюта="EUR", объект="о2"))
    games_db.предложить(с, E2, "причина")
    games_db.запомнить_игру(с, игра(E3, "Другая валюта", цена=1999, валюта="GBP", объект="о3"))
    games_db.предложить(с, E3, "причина")
    записи = {
        "о1": игра(E1, "Без цены", цена=None, валюта="", объект="о1"),
        "о2": игра(E2, "С ценой", цена=2799, валюта="EUR", объект="о2"),
        "о3": игра(E3, "Другая валюта", цена=None, валюта="", объект="о3"),
    }

    пересобрать(с, магазины(игра_eshop=lambda о: записи[о]), steam_сменилась=False,
                eshop="та_же_зона", страны={"steam": "KZ", "eshop": "FR"})

    запись = games_db.игра(с, E1)
    assert (запись["цена"], запись["цена_без_скидки"], запись["скидка"], запись["валюта"],
            запись["скидка_до"]) == (1999, 2499, 20, "EUR", "2026-11-01")
    assert games_db.игра(с, E2)["цена"] == 2799
    # Валюта прежней цены другая — она несравнима, пустая цена записи честнее.
    assert games_db.игра(с, E3)["цена"] is None


