def test_обрыв_на_середине_применения_хранилище_прежнее():
    с = _хранилище_для_обрыва()
    до = _снимок(с)
    # Обрыв после удалений и замены номера, на сбросе цен eShop.
    с.execute("CREATE TEMP TRIGGER обрыв BEFORE DELETE ON price_history "
              "WHEN old.номер > 70000000000000 BEGIN SELECT RAISE(ABORT, 'обрыв'); END")

    with pytest.raises(sqlite3.IntegrityError):
        пересобрать(с, _магазины_для_обрыва(), steam_сменилась=True, eshop="другая_зона",
                    страны={"steam": "KZ", "eshop": "US"})

    assert _снимок(с) == до
    assert (games_db.страна_steam(с), games_db.страна_eshop(с)) == ("RU", "DE")


