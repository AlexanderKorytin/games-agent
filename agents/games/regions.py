"""Смена региона: пересборка хранилища под новую страну Steam и eShop (дизайн, «Как устроено»,
пункт «Смена региона»).

Пересобираются игры «в работе» (`games_db.номера_в_работе`: предложения с любой оценкой — в том
числе желаемое, это предложения с плюсом, — и календарь, без купленных). Библиотека и список
желаемого Steam — данные самого Steam — не трогаются. Запреты карточки тоже: их пишет человек.

Сети модуль не знает: магазины новой страны приходят полями `Магазины`, `jobs.py` он не ввозит
(кольцо). Ход ведёт программа, модель не участвует.

Сбой магазина на одной игре — не удаление: игра остаётся как была, её имя идёт в «не проверено».
Удаляется только игра, которой в новой стране точно нет.
"""

from __future__ import annotations

import sqlite3
from collections.abc import Awaitable, Callable
from dataclasses import dataclass, field, replace
from typing import Literal

import eshop_store as es
import games_db
import steam_store as ss

Eshop = Literal["та_же_зона", "другая_зона", "без_изменений", "выключен"]
ДОВОДЫ_ESHOP = ("та_же_зона", "другая_зона", "без_изменений", "выключен")


async def _не_задано(*_) -> None:
    raise RuntimeError("магазин для этой ветви пересборки не передан")


@dataclass
class Магазины:
    """Магазины НОВОЙ страны (кроме `прежняя_eshop`). Всё асинхронно; сбой — `ss.ОшибкаМагазина`.

    - `игра_steam(номер)` — игра Steam в новой стране; `None` — её там нет (`success:false`).
    - `игра_eshop(объект)` — запись каталога новой страны по коду `objectID`, с ценой, адресом и
      описанием страны; `None` — записи нет (игры нет в продаже).
    - `найти_eshop(название)` — поиск каталога новой страны по названию.
    - `прежняя_eshop(объект)` — запись каталога ПРЕЖНЕЙ страны: платформы игры (`Игра.платформы`),
      в хранилище их нет. `None` — записи нет, платформа неизвестна.
    - `пара_eshop(игра_steam)` — та же игра в eShop новой страны (`eshop.найти_в_eshop`).

    Ветви, которой поле не нужно, его можно не передавать: незаданное поле при вызове падает."""

    игра_steam: Callable[[int], Awaitable[ss.Игра | None]] = _не_задано
    игра_eshop: Callable[[str], Awaitable[ss.Игра | None]] = _не_задано
    найти_eshop: Callable[[str], Awaitable[list[ss.Игра]]] = _не_задано
    прежняя_eshop: Callable[[str], Awaitable[ss.Игра | None]] = _не_задано
    пара_eshop: Callable[[ss.Игра], Awaitable[ss.Игра | None]] = _не_задано


@dataclass
class Итог:
    """Имена игр по исходам; имя — из хранилища до пересборки (то, что человек видел)."""

    обновлено: list[str] = field(default_factory=list)
    удалено: list[str] = field(default_factory=list)
    не_проверено: list[str] = field(default_factory=list)
    # Поиск пары eShop для игры Steam упал: строки `pairs` нет, задания поищут снова.
    пары_не_сверены: list[str] = field(default_factory=list)

    def текст(self) -> str:
        части = [
            f"обновлено {len(self.обновлено)}",
            _со_списком("удалено", self.удалено),
            _со_списком("не проверено", self.не_проверено),
        ]
        текст = "Регион сменён: " + ", ".join(части)
        if self.пары_не_сверены:
            текст += "; " + _со_списком("пара eShop не сверена:", self.пары_не_сверены)
        return текст


def _со_списком(слово: str, имена: list[str]) -> str:
    return f"{слово} {len(имена)}" + (f" ({', '.join(имена)})" if имена else "")


@dataclass
class _План:
    """Всё, что пересборка запишет, — собрано из ответов магазинов до первой записи."""

    запомнить: list[ss.Игра] = field(default_factory=list)
    заменить: list[tuple[int, int]] = field(default_factory=list)
    удалить: list[int] = field(default_factory=list)
    сбросить_цены_steam: bool = False
    сбросить_цены_eshop: bool = False
    сбросить_пары: bool = False
    пары: list[tuple[int, ss.Игра | None]] = field(default_factory=list)


async def пересобрать(
    с: sqlite3.Connection, магазины: Магазины, *, steam_сменилась: bool, eshop: Eshop,
    страны: dict[str, str] | None = None,
) -> Итог:
    """Пересобирает игры в работе под новую страну и пишет итог в ленту (род «итог»).

    **Атомарно.** Сначала все ответы магазинов собираются без записи; затем одной транзакцией
    (`games_db.транзакция`) применяются карточки, замены номеров, удаления, сбросы цен и пар,
    новые пары, страны (`страны` — доводы `задать_страны`: `{"steam": "KZ", "eshop": "US"}`;
    `None` — страны ставит вызывающий) и итог в ленту. Исключение на сборе — не записано ничего;
    обрыв применения — откат целиком. Повтор безопасен.

    `steam_сменилась` — каждая игра Steam берётся заново: `None` — удаляется, иначе карточка
    обновляется (прежняя сводка отзывов не стирается пустой); цены и история цен Steam сброшены —
    сменилась валюта. Цены eShop не трогаются.

    `eshop`:
    - «та_же_зона» — номера те же. Каждая игра берётся записью каталога новой страны по `объект`
      целиком (цена, адрес, описание страны). Записи нет — игры нет в продаже, удаляется; запись
      с другим номером — номер заменяется. Кода каталога нет — «не проверено». Цены и история
      eShop сброшены; пары верны — номера не менялись.
    - «другая_зона» — номера другие. Каждая игра ищется по точному `es.сравнимое` имени и той же
      платформе (платформы — из записи прежней страны, `прежняя_eshop`; сначала совпадение набора
      платформ, затем общая платформа; платформа неизвестна — первое точное имя). Нашлась —
      карточка новой и `заменить_номер` (оценка, причина, календарь, «уже играл» переезжают);
      нет — удаляется. Имя без латиницы и цифр (пустой ключ) не ищется: «не проверено». Цены и
      история eShop сброшены, все пары сброшены; для каждой оставшейся игры Steam с карточкой
      пара ищется заново (`пара_eshop`).
    - «без_изменений», «выключен» — eShop не трогается.

    Сбой магазина на одной игре (`ss.ОшибкаМагазина`) — игра остаётся как была, имя в «не
    проверено» (у пары — в «пара eShop не сверена»). Иные исключения — наверх, без записи."""
    if eshop not in ДОВОДЫ_ESHOP:
        raise ValueError(f"довод eshop {eshop!r}: допустимы {', '.join(ДОВОДЫ_ESHOP)}")
    итог, план = Итог(), _План()
    в_работе = games_db.номера_в_работе(с)
    имена = {н: _имя(с, н) for н in в_работе}
    свежие_steam: dict[int, ss.Игра] = {}

    if steam_сменилась:
        for номер in (н for н in в_работе if not es.это_eshop(н)):
            try:
                игра = await магазины.игра_steam(номер)
            except ss.ОшибкаМагазина:
                итог.не_проверено.append(имена[номер])
                continue
            if игра is None:
                план.удалить.append(номер)
                итог.удалено.append(имена[номер])
                continue
            игра = _с_прежними_отзывами(с, игра, номер)
            план.запомнить.append(игра)
            свежие_steam[номер] = игра
            итог.обновлено.append(имена[номер])
        план.сбросить_цены_steam = True

    номера_eshop = [н for н in в_работе if es.это_eshop(н)]
    if eshop in ("та_же_зона", "другая_зона"):
        собрать = _в_той_же_зоне if eshop == "та_же_зона" else _в_другой_зоне
        for номер in номера_eshop:
            await собрать(с, магазины, номер, имена[номер], итог, план)
        план.сбросить_цены_eshop = True
    if eshop == "другая_зона":
        план.сбросить_пары = True
        for номер in в_работе:
            if es.это_eshop(номер) or номер in план.удалить:
                continue
            игра = свежие_steam.get(номер) or _игра_из_карточки(с, номер)
            if игра is None:
                continue  # карточки нет — искать пару не по чему; задания поищут сами
            try:
                план.пары.append((номер, await магазины.пара_eshop(игра)))
            except ss.ОшибкаМагазина:
                итог.пары_не_сверены.append(игра.имя)

    _применить(с, план, итог, страны)
    return итог


def _применить(с: sqlite3.Connection, план: _План, итог: Итог, страны: dict[str, str] | None) -> None:
    with games_db.транзакция(с) as т:
        for игра in план.запомнить:
            т.запомнить_игру(игра)
        for старый, новый in план.заменить:
            т.заменить_номер(старый, новый)
        for номер in план.удалить:
            т.удалить_игру(номер)
        if план.сбросить_цены_steam:
            т.сбросить_цены(eshop=False)
        if план.сбросить_цены_eshop:
            т.сбросить_цены(eshop=True)
        if план.сбросить_пары:
            т.сбросить_пары()
        for номер, пара in план.пары:
            if пара is not None:
                т.запомнить_игру(пара)
            т.записать_пару(номер, пара.номер if пара else None)
        if страны:
            т.задать_страны(**страны)
        т.в_ленту("итог", итог.текст())


async def _в_той_же_зоне(
    с: sqlite3.Connection, магазины: Магазины, номер: int, имя: str, итог: Итог, план: _План
) -> None:
    объект = (games_db.игра(с, номер) or {}).get("объект")
    if not объект:
        итог.не_проверено.append(имя)
        return
    try:
        запись = await магазины.игра_eshop(объект)
    except ss.ОшибкаМагазина:
        итог.не_проверено.append(имя)
        return
    if запись is None:
        план.удалить.append(номер)
        итог.удалено.append(имя)
        return
    план.запомнить.append(_с_прежними_отзывами(с, запись, номер))
    if запись.номер != номер:
        план.заменить.append((номер, запись.номер))
    итог.обновлено.append(имя)


async def _в_другой_зоне(
    с: sqlite3.Connection, магазины: Магазины, номер: int, имя: str, итог: Итог, план: _План
) -> None:
    запись = games_db.игра(с, номер) or {}
    ключ = es.сравнимое(запись.get("имя") or "")
    if not ключ:
        итог.не_проверено.append(имя)
        return
    try:
        объект = запись.get("объект")
        прежняя = await магазины.прежняя_eshop(объект) if объект else None
        выдача = await магазины.найти_eshop(es.чистое_имя(запись["имя"]))
    except ss.ОшибкаМагазина:
        итог.не_проверено.append(имя)
        return
    новая = _та_же(выдача, ключ, set(прежняя.платформы) if прежняя else set())
    if новая is None:
        план.удалить.append(номер)
        итог.удалено.append(имя)
        return
    план.запомнить.append(_с_прежними_отзывами(с, новая, номер))
    план.заменить.append((номер, новая.номер))
    итог.обновлено.append(имя)


def _та_же(выдача: list[ss.Игра], ключ: str, платформы: set[str]) -> ss.Игра | None:
    """Первая запись выдачи с тем же именем: с тем же набором платформ, иначе с общей платформой.
    Платформы неизвестны — первая с тем же именем."""
    по_имени = [и for и in выдача if es.сравнимое(и.имя) == ключ]
    if not платформы:
        return по_имени[0] if по_имени else None
    for подходит in (lambda и: set(и.платформы) == платформы,
                     lambda и: bool(set(и.платформы) & платформы)):
        for и in по_имени:
            if подходит(и):
                return и
    return None


def _имя(с: sqlite3.Connection, номер: int) -> str:
    запись = games_db.игра(с, номер)
    return (запись or {}).get("имя") or f"№{номер}"


def _игра_из_карточки(с: sqlite3.Connection, номер: int) -> ss.Игра | None:
    """Игра Steam по карточке хранилища — для поиска пары нужно только имя."""
    запись = games_db.игра(с, номер)
    return ss.Игра(номер=номер, имя=запись["имя"]) if запись else None


def _с_прежними_отзывами(с: sqlite3.Connection, игра: ss.Игра, прежний_номер: int) -> ss.Игра:
    """Игра без сводки отзывов (Steam без `appreviews`, запись eShop без Metacritic) не стирает
    прежнюю сводку той же игры — она хранится под прежним номером."""
    if игра.отзывы.всего > 0:
        return игра
    запись = games_db.игра(с, прежний_номер)
    if запись and запись.get("отзывы_всего"):
        return replace(игра, отзывы=ss.Отзывы(
            запись.get("отзывы_сводка") or "", int(запись.get("отзывы_положительных") or 0),
            int(запись["отзывы_всего"]),
        ))
    return игра
