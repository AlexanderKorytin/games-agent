"""Смена региона: пересборка хранилища под новую страну Steam и eShop (дизайн, «Как устроено»,
пункт «Смена региона»).

Пересобираются игры «в работе» (`games_db.номера_в_работе`: предложения с любой оценкой — в том
числе желаемое, это предложения с плюсом, — и календарь, без купленных). Библиотека и список
желаемого Steam — данные самого Steam — не трогаются. Запреты карточки тоже: их пишет человек.

Сети модуль не знает: магазины новой страны приходят полями `Магазины`, `jobs.py` он не ввозит
(кольцо). Ход ведёт программа, модель не участвует.

Сбой магазина на одной игре — не удаление: игра остаётся как была, её имя идёт в «не проверено».
Удаляется только игра, которой в новой стране точно нет.
"""

from __future__ import annotations

import sqlite3
from collections.abc import Awaitable, Callable
from dataclasses import dataclass, field, replace
from typing import Literal

import eshop_store as es
import games_db
import steam_store as ss

Eshop = Literal["та_же_зона", "другая_зона", "без_изменений", "выключен"]
ДОВОДЫ_ESHOP = ("та_же_зона", "другая_зона", "без_изменений", "выключен")


async def _не_задано(*_) -> None:
    raise RuntimeError("магазин для этой ветви пересборки не передан")


@dataclass
class Магазины:
    """Магазины НОВОЙ страны (кроме `прежняя_eshop`). Всё асинхронно; сбой — `ss.ОшибкаМагазина`.

    - `игра_steam(номер)` — игра Steam в новой стране; `None` — её там нет (`success:false`).
    - `игра_eshop(объект)` — запись каталога новой страны по коду `objectID`, с ценой, адресом и
      описанием страны; `None` — записи нет (игры нет в продаже).
    - `найти_eshop(название)` — поиск каталога новой страны по названию.
    - `прежняя_eshop(объект)` — запись каталога ПРЕЖНЕЙ страны: платформы игры (`Игра.платформы`),
      в хранилище их нет. `None` — записи нет, платформа неизвестна.
    - `пара_eshop(игра_steam)` — та же игра в eShop новой страны (`eshop.найти_в_eshop`).

    Ветви, которой поле не нужно, его можно не передавать: незаданное поле при вызове падает."""

    игра_steam: Callable[[int], Awaitable[ss.Игра | None]] = _не_задано
    игра_eshop: Callable[[str], Awaitable[ss.Игра | None]] = _не_задано
    найти_eshop: Callable[[str], Awaitable[list[ss.Игра]]] = _не_задано
    прежняя_eshop: Callable[[str], Awaitable[ss.Игра | None]] = _не_задано
    пара_eshop: Callable[[ss.Игра], Awaitable[ss.Игра | None]] = _не_задано


@dataclass
class Итог:
    """Имена игр по исходам; имя — из хранилища до пересборки (то, что человек видел)."""

    обновлено: list[str] = field(default_factory=list)
    удалено: list[str] = field(default_factory=list)
    не_проверено: list[str] = field(default_factory=list)
    # «Другая зона»: игры eShop, которые не удалось сверить (сбой, имя без латиницы, новый номер
    # уже занят другой старой записью этого прохода либо другой игрой в работе), — остались на
    # номерах прежней зоны.
    остались_на_прежних: list[str] = field(default_factory=list)
    # Игра в работе и в списке желаемого Steam, которой нет в новой стране: снята из подбора,
    # карточка осталась (список ведёт Steam).
    снято: list[str] = field(default_factory=list)
    # Список желаемого Steam вне работы: игры нет в новой стране, но список ведёт Steam —
    # карточка остаётся.
    нет_в_регионе: list[str] = field(default_factory=list)
    # Пара eShop игры Steam не сверена (сбой поиска либо записи каталога): строки `pairs` нет.
    # Снова её ищет только `jobs._связать_с_eshop` — при отборе новой игры и для желаемого
    # (`_скидки_eshop`); у предложения без плюса и игры календаря пары не будет до следующей
    # смены зоны eShop.
    пары_не_сверены: list[str] = field(default_factory=list)
    # «Та же зона»: записи eShop-пары игры Steam нет в продаже в новой стране — пара снята,
    # плашка eShop у игры Steam пропала.
    пары_нет_в_продаже: list[str] = field(default_factory=list)

    def текст(self) -> str:
        части = [
            f"обновлено {len(self.обновлено)}",
            _со_списком("удалено", self.удалено),
            _со_списком("не проверено", self.не_проверено),
        ]
        текст = "Регион сменён: " + ", ".join(части)
        if self.остались_на_прежних:
            текст += (
                "; " + _со_списком("не проверено в eShop", self.остались_на_прежних)
                + " — остались на прежних номерах, сверьте вручную или смените регион ещё раз позже"
            )
        if self.снято:
            текст += "; " + _со_списком(
                "снято из подбора (осталась в списке желаемого Steam):", self.снято)
        if self.нет_в_регионе:
            текст += "; " + _со_списком("в списке желаемого Steam нет в регионе:", self.нет_в_регионе)
        if self.пары_не_сверены:
            текст += "; " + _со_списком("пара eShop не сверена:", self.пары_не_сверены)
        if self.пары_нет_в_продаже:
            текст += "; " + _со_списком(
                "пара eShop снята — нет в продаже в новой стране:", self.пары_нет_в_продаже)
        return текст


def _со_списком(слово: str, имена: list[str]) -> str:
    return f"{слово} {len(имена)}" + (f" ({', '.join(имена)})" if имена else "")


@dataclass
class _План:
    """Всё, что пересборка запишет, — собрано из ответов магазинов до первой записи."""

    запомнить: list[ss.Игра] = field(default_factory=list)
    заменить: list[tuple[int, int]] = field(default_factory=list)
    удалить: list[int] = field(default_factory=list)
    # Игры списка желаемого Steam, которых нет в новой стране: решения сняты, карточка остаётся,
    # цена прежней страны стёрта.
    снять: list[int] = field(default_factory=list)
    стереть_цену: list[int] = field(default_factory=list)
    сбросить_цены_steam: bool = False
    сбросить_цены_eshop: bool = False
    сбросить_пары: bool = False
    # Карточки eShop-пар, которые не удалось взять заново: карточка и пары уходят, отказы модели
    # остаются (`games_db.Запись.забыть_карточку`).
    забыть: list[int] = field(default_factory=list)
    пары: list[tuple[int, ss.Игра | None]] = field(default_factory=list)


async def пересобрать(
    с: sqlite3.Connection, магазины: Магазины, *, steam_сменилась: bool, eshop: Eshop,
    страны: dict[str, str],
) -> Итог:
    """Пересобирает игры в работе под новую страну и пишет итог в ленту (род «итог»).

    **Атомарно.** Сначала все ответы магазинов собираются без записи; затем одной транзакцией
    (`games_db.транзакция`) применяются карточки, замены номеров, удаления, сбросы цен и пар,
    новые пары, страны (`страны` — обязательные доводы `задать_страны`, например
    `{"steam": "KZ", "eshop": "US"}`: страны и данные меняются вместе) и итог в ленту.
    Исключение на сборе — не записано ничего; обрыв применения — откат целиком. Повтор безопасен
    только после такого отката: страны в хранилище ещё прежние.

    После успешной пересборки страны уже новые. Повторная «другая_зона» к той же стране не
    запускается: страна eShop не изменилась — вызывающий передаёт «без_изменений». Игры, что
    остались «не проверено» в ветви «другая_зона», живут на номерах прежней зоны; итог ленты
    так и говорит: сверить вручную или сменить регион ещё раз позже.

    `steam_сменилась` — каждая игра Steam берётся заново: `None` — удаляется (а если она и в
    списке желаемого Steam — сняты только её решения: предложение, календарь, «уже играл»,
    отказы; карточка остаётся, список ведёт Steam, цена прежней страны стёрта; в итоге —
    «снято из подбора (осталась в списке желаемого Steam)»), иначе карточка
    обновляется (прежняя сводка отзывов не стирается пустой); цены и история цен Steam сброшены —
    сменилась валюта. Цены eShop не трогаются. Игры списка желаемого Steam вне работы тоже
    берутся заново и пишутся карточкой; `None` — карточка остаётся (список ведёт Steam) с
    пустой ценой (цена прежней страны несравнима), имя — в «в списке желаемого Steam нет в
    регионе»; сбой — карточка и цена прежние, имя — в «не проверено».

    `eshop`:
    - «та_же_зона» — номера те же. Каждая игра берётся записью каталога новой страны по `объект`
      целиком (цена, адрес, описание страны). Записи нет — игры нет в продаже, удаляется; запись
      с другим номером — номер заменяется. Кода каталога нет — «не проверено». Запись без цены
      не затирает прежнюю цену карточки, если её валюта — валюта новой страны (страны Европы с
      одной валютой, DE → FR); валюта новой страны берётся из записей этого же прохода с ценой,
      неизвестна — цена пустая. Цены и история eShop сброшены; пары верны — номера не менялись.
      Карточки eShop, что служат парой игре Steam (в работе либо в списке желаемого Steam), но
      сами не в работе, берутся заново тем же путём — плашка игры Steam показывает их цену и
      адрес: запись есть — карточка новой страны (другой номер — пара переезжает на него); записи
      нет — карточка удаляется, пара снята («искали, не нашли»), игра Steam цела, её имя — в
      «пара eShop снята — нет в продаже»; кода каталога нет или сбой — карточка и пара забыты,
      отказ модели по записи остаётся, имя игры Steam — в «пара eShop не сверена» (снова пару
      ищет только `jobs._связать_с_eshop`: при отборе и для желаемого). В «обновлено» и
      «удалено» карточки пар не идут.
    - «другая_зона» — номера другие. Каждая игра ищется по точному `es.сравнимое` имени и той же
      платформе (платформы — из записи прежней страны, `прежняя_eshop`; сначала совпадение набора
      платформ, затем общая платформа; платформа неизвестна — первое точное имя). Нашлась —
      карточка новой и `заменить_номер` (оценка, причина, календарь, «уже играл» переезжают);
      нет — удаляется. Имя без латиницы и цифр (пустой ключ) не ищется. Новый номер уже занят
      другой старой записью этого прохода (издания Switch и Switch 2 сошлись в одну запись) либо
      другой игрой в работе — запись не переносится: оценка не теряется молча (то же и в «той же
      зоне», там такая игра — «не проверено»). Такие игры и сбои — `остались_на_прежних`
      (номера прежней зоны). Цены и
      история eShop сброшены, все пары сброшены; для каждой оставшейся игры Steam с карточкой
      пара ищется заново (`пара_eshop`).
    - «без_изменений», «выключен» — eShop не трогается.

    Сбой магазина на одной игре (`ss.ОшибкаМагазина`) — игра остаётся как была, имя в «не
    проверено» (у пары — в «пара eShop не сверена»). Иные исключения — наверх, без записи."""
    if eshop not in ДОВОДЫ_ESHOP:
        raise ValueError(f"довод eshop {eshop!r}: допустимы {', '.join(ДОВОДЫ_ESHOP)}")
    итог, план = Итог(), _План()
    в_работе = games_db.номера_в_работе(с)
    имена = {н: _имя(с, н) for н in в_работе}
    свежие_steam: dict[int, ss.Игра] = {}

    if steam_сменилась:
        список_steam = games_db.список_steam(с)
        for номер in (н for н in в_работе if not es.это_eshop(н)):
            try:
                игра = await магазины.игра_steam(номер)
            except ss.ОшибкаМагазина:
                итог.не_проверено.append(имена[номер])
                continue
            if игра is None:
                if номер in список_steam:
                    план.снять.append(номер)
                    план.стереть_цену.append(номер)
                    итог.снято.append(имена[номер])
                else:
                    план.удалить.append(номер)
                    итог.удалено.append(имена[номер])
                continue
            игра = _с_прежними_отзывами(с, игра, номер)
            план.запомнить.append(игра)
            свежие_steam[номер] = игра
            итог.обновлено.append(имена[номер])
        # Список желаемого Steam вне работы: карточки — тоже в новой валюте.
        список = sorted(список_steam - set(в_работе) - games_db.куплены(с))
        for номер in список:
            имя = _имя(с, номер)
            try:
                игра = await магазины.игра_steam(номер)
            except ss.ОшибкаМагазина:
                итог.не_проверено.append(имя)
                continue
            if игра is None:
                план.стереть_цену.append(номер)
                итог.нет_в_регионе.append(имя)
                continue
            план.запомнить.append(_с_прежними_отзывами(с, игра, номер))
            итог.обновлено.append(имя)
        план.сбросить_цены_steam = True

    номера_eshop = [н for н in в_работе if es.это_eshop(н)]
    if eshop == "та_же_зона":
        await _в_той_же_зоне(с, магазины, номера_eshop, set(в_работе), имена, итог, план)
        план.сбросить_цены_eshop = True
    elif eshop == "другая_зона":
        for номер in номера_eshop:
            await _в_другой_зоне(с, магазины, номер, set(в_работе), имена[номер], итог, план)
        план.сбросить_цены_eshop = True
    if eshop == "другая_зона":
        план.сбросить_пары = True
        for номер in в_работе:
            if es.это_eshop(номер) or номер in план.удалить or номер in план.снять:
                continue
            игра = свежие_steam.get(номер) or _игра_из_карточки(с, номер)
            if игра is None:
                continue  # карточки нет — искать пару не по чему
            try:
                план.пары.append((номер, await магазины.пара_eshop(игра)))
            except ss.ОшибкаМагазина:
                итог.пары_не_сверены.append(игра.имя)

    _применить(с, план, итог, страны)
    return итог


def _применить(с: sqlite3.Connection, план: _План, итог: Итог, страны: dict[str, str]) -> None:
    with games_db.транзакция(с) as т:
        for игра in план.запомнить:
            т.запомнить_игру(игра)
        for старый, новый in план.заменить:
            т.заменить_номер(старый, новый)
        for номер in план.удалить:
            т.удалить_игру(номер)
        for номер in план.снять:
            т.снять_из_работы(номер)
        for номер in план.забыть:
            т.забыть_карточку(номер)
        for номер in план.стереть_цену:
            т.обновить_цену(номер, цена=None, цена_без_скидки=None, скидка=0, валюта="",
                            скидка_до="")
        if план.сбросить_цены_steam:
            т.сбросить_цены(eshop=False)
        if план.сбросить_цены_eshop:
            т.сбросить_цены(eshop=True)
        if план.сбросить_пары:
            т.сбросить_пары()
        for номер, пара in план.пары:
            if пара is not None:
                т.запомнить_игру(пара)
            т.записать_пару(номер, пара.номер if пара else None)
        т.задать_страны(**страны)
        т.в_ленту("итог", итог.текст())


async def _в_той_же_зоне(
    с: sqlite3.Connection, магазины: Магазины, номера: list[int], в_работе: set[int],
    имена: dict[int, str], итог: Итог, план: _План,
) -> None:
    найдены: list[tuple[int, ss.Игра]] = []
    for номер in номера:
        try:
            запись = await _запись_страны(с, магазины, номер)
        except _НеПроверено:
            итог.не_проверено.append(имена[номер])
            continue
        if запись is None:
            план.удалить.append(номер)
            итог.удалено.append(имена[номер])
            continue
        найдены.append((номер, запись))
    свежие = {з.номер for _, з in найдены}
    пары: list[tuple[int, list[int], ss.Игра]] = []
    for пара_, игры_steam in _пары_steam(с, в_работе, план).items():
        if пара_ in свежие:
            continue  # карточку уже берёт заново игра в работе с этим номером
        try:
            запись = await _запись_страны(с, магазины, пара_)
        except _НеПроверено:
            # Карточка с ценой прежней страны не остаётся, пара не сверена; отказ модели по
            # записи цел. Снова пару ищет только `jobs._связать_с_eshop` (см. `пары_не_сверены`).
            план.забыть.append(пара_)
            итог.пары_не_сверены.extend(_имя(с, н) for н in игры_steam)
            continue
        if запись is None:
            # Игры нет в продаже в новой стране: пара снята («искали, не нашли»), игра Steam цела.
            план.удалить.append(пара_)
            план.пары.extend((н, None) for н in игры_steam)
            итог.пары_нет_в_продаже.extend(_имя(с, н) for н in игры_steam)
            continue
        пары.append((пара_, игры_steam, запись))
    записи = [з for _, з in найдены] + [з for *_, з in пары]
    валюта = next((з.валюта for з in записи if з.цена is not None and з.валюта), "")
    for номер, запись in найдены:
        запись = _с_прежней_ценой(с, запись, номер, валюта)
        if not _перенести(план, номер, _с_прежними_отзывами(с, запись, номер), в_работе):
            итог.не_проверено.append(имена[номер])
            continue
        итог.обновлено.append(имена[номер])
    for пара_, игры_steam, запись in пары:
        запись = _с_прежними_отзывами(с, _с_прежней_ценой(с, запись, пара_, валюта), пара_)
        if запись.номер == пара_:
            план.запомнить.append(запись)
            continue
        # Запись страны под другим номером: прежняя карточка уходит, пара — на новую.
        план.удалить.append(пара_)
        план.пары.extend((н, запись) for н in игры_steam)


class _НеПроверено(Exception):
    """Запись каталога новой страны не взята: кода каталога нет либо сбой магазина."""


async def _запись_страны(с: sqlite3.Connection, магазины: Магазины, номер: int) -> ss.Игра | None:
    """Запись каталога новой страны по коду `объект` карточки; `None` — игры нет в продаже."""
    объект = (games_db.игра(с, номер) or {}).get("объект")
    if not объект:
        raise _НеПроверено
    try:
        return await магазины.игра_eshop(объект)
    except ss.ОшибкаМагазина as exc:
        raise _НеПроверено from exc


def _пары_steam(с: sqlite3.Connection, в_работе: set[int], план: _План) -> dict[int, list[int]]:
    """Карточки eShop, что служат парой игре Steam (её плашка показывает их цену и адрес), но
    сами не в работе: номер карточки → игры Steam. Игры Steam — в работе и в списке желаемого
    Steam без купленных; удаляемые этой пересборкой не берутся — их пары уходят вместе с ними."""
    игры_steam = (
        {н for н in в_работе if not es.это_eshop(н)}
        | (games_db.список_steam(с) - games_db.куплены(с))
    ) - set(план.удалить)
    пары: dict[int, list[int]] = {}
    for номер in sorted(игры_steam):
        пара_ = games_db.пара(с, номер)
        if пара_ is not None and es.это_eshop(пара_) and пара_ not in в_работе:
            пары.setdefault(пара_, []).append(номер)
    return пары


def _перенести(план: _План, номер: int, новая: ss.Игра, в_работе: set[int]) -> bool:
    """Карточка новой записи и замена номера в план. `False` — новый номер уже занят: другой
    старой записью этого прохода либо другой игрой в работе (издания сошлись в один номер).
    Запись не переносится — `заменить_номер` оставил бы строку занявшей номер игры и молча
    стёр бы оценку переносимой. Занявшая игра в работе сама могла бы уехать или удалиться этим
    же проходом — запись всё равно не переносится: порядок замен не важен, решение не теряется."""
    if новая.номер != номер:
        if новая.номер in в_работе or any(занят == новая.номер for _, занят in план.заменить):
            return False
        план.заменить.append((номер, новая.номер))
    план.запомнить.append(новая)
    return True


def _с_прежней_ценой(с: sqlite3.Connection, запись: ss.Игра, номер: int, валюта: str) -> ss.Игра:
    """Запись без цены не затирает прежнюю цену карточки той же валюты (`валюта` — валюта новой
    страны; "" — неизвестна)."""
    if запись.цена is not None or not валюта:
        return запись
    прежняя = games_db.игра(с, номер) or {}
    if прежняя.get("цена") is None or прежняя.get("валюта") != валюта:
        return запись
    return replace(
        запись, цена=прежняя["цена"], цена_без_скидки=прежняя.get("цена_без_скидки"),
        скидка=прежняя.get("скидка") or 0, валюта=валюта, скидка_до=прежняя.get("скидка_до") or "",
        бесплатна=bool(прежняя.get("бесплатна")),
    )


async def _в_другой_зоне(
    с: sqlite3.Connection, магазины: Магазины, номер: int, в_работе: set[int], имя: str,
    итог: Итог, план: _План,
) -> None:
    запись = games_db.игра(с, номер) or {}
    ключ = es.сравнимое(запись.get("имя") or "")
    if not ключ:
        итог.остались_на_прежних.append(имя)
        return
    try:
        объект = запись.get("объект")
        прежняя = await магазины.прежняя_eshop(объект) if объект else None
        выдача = await магазины.найти_eshop(es.чистое_имя(запись["имя"]))
    except ss.ОшибкаМагазина:
        итог.остались_на_прежних.append(имя)
        return
    новая = _та_же(выдача, ключ, set(прежняя.платформы) if прежняя else set())
    if новая is None:
        план.удалить.append(номер)
        итог.удалено.append(имя)
        return
    if not _перенести(план, номер, _с_прежними_отзывами(с, новая, номер), в_работе):
        итог.остались_на_прежних.append(имя)
        return
    итог.обновлено.append(имя)


def _та_же(выдача: list[ss.Игра], ключ: str, платформы: set[str]) -> ss.Игра | None:
    """Первая запись выдачи с тем же именем: с тем же набором платформ, иначе с общей платформой.
    Платформы неизвестны — первая с тем же именем."""
    по_имени = [и for и in выдача if es.сравнимое(и.имя) == ключ]
    if not платформы:
        return по_имени[0] if по_имени else None
    for подходит in (lambda и: set(и.платформы) == платформы,
                     lambda и: bool(set(и.платформы) & платформы)):
        for и in по_имени:
            if подходит(и):
                return и
    return None


def _имя(с: sqlite3.Connection, номер: int) -> str:
    запись = games_db.игра(с, номер)
    return (запись or {}).get("имя") or f"№{номер}"


def _игра_из_карточки(с: sqlite3.Connection, номер: int) -> ss.Игра | None:
    """Игра Steam по карточке хранилища — для поиска пары нужно только имя."""
    запись = games_db.игра(с, номер)
    return ss.Игра(номер=номер, имя=запись["имя"]) if запись else None


def _с_прежними_отзывами(с: sqlite3.Connection, игра: ss.Игра, прежний_номер: int) -> ss.Игра:
    """Игра без сводки отзывов (Steam без `appreviews`, запись eShop без Metacritic) не стирает
    прежнюю сводку той же игры — она хранится под прежним номером."""
    if игра.отзывы.всего > 0:
        return игра
    запись = games_db.игра(с, прежний_номер)
    if запись and запись.get("отзывы_всего"):
        return replace(игра, отзывы=ss.Отзывы(
            запись.get("отзывы_сводка") or "", int(запись.get("отзывы_положительных") or 0),
            int(запись["отзывы_всего"]),
        ))
    return игра
