class УжеИдёт(RuntimeError):
    """Задание того же рода уже идёт в другом процессе (кнопка веба и служба launchd)."""


def _замок(род: str):
    """Замок файла на род задания: веб и служба — разные процессы, и без него оба считали бы
    «нужно = 10 − открытых» и довели бы открытые предложения до 20. Не блокирует: занят —
    `УжеИдёт`."""
    путь = agent_env.данные() / f"задание-{род}.lock"
    путь.parent.mkdir(parents=True, exist_ok=True)
    файл = open(путь, "w")
    try:
        fcntl.flock(файл, fcntl.LOCK_EX | fcntl.LOCK_NB)
    except BlockingIOError:
        файл.close()
        raise УжеИдёт(f"задание «{род}» уже идёт") from None
    return файл


НЕТ_СТРАНЫ_STEAM = "страна Steam не выбрана — укажите в настройках агента"


def _страна_steam_или_строка(с) -> str | None:
    """Страна Steam человека. Её нет — одна строка в ленте, пока не появится (отметка
    «нет_страны_steam», как у ключа Steam), без уведомления каждый день: задания без страны не
    идут, магазин наугад не выбирается. Страна есть — отметка снята."""
    страна = games_db.страна_steam(с)
    if страна:
        if games_db.отметка(с, "нет_страны_steam"):
            games_db.поставить_отметку(с, "нет_страны_steam", "")
        return страна
    if not games_db.отметка(с, "нет_страны_steam"):
        _в_ленту(с, "сбой", "Укажите страну Steam в настройках: без неё задания не идут — не знаю, "
                 "в магазин какой страны ходить.")
        games_db.поставить_отметку(с, "нет_страны_steam", _сегодня())
    return None


async def запустить(род: str, каталог: Path | None = None) -> str:
    """Магазины Steam и eShop, оценки Metacritic, учётка по ключу, местная модель, RAG. Сбой — в
    ленту, затем наверх.

    Страны магазинов — из хранилища (выбор человека): Steam и IsThereAnyDeal — страна Steam,
    eShop — его страна (`_регион_eshop`). Страны Steam нет — задание не идёт, итог говорит, что
    сделать; это не сбой: отметки сбоя и уведомления нет."""
    import itad
    import metacritic
    import steam_account

    каталог = каталог or Path.cwd()
    имя = ИМЕНА[род]
    тайны = secrets_store.Тайны()
    клиент_модели = None
    замок = None
    try:
        замок = _замок(род)
        с = games_db.открыть()
        try:
            страна = _страна_steam_или_строка(с)
            регион = _регион_eshop(с)
        finally:
            с.close()
        if страна is None:
            # Не начато: отметки «начато» нет, догоняющего запуска тоже (`нужен_догоняющий`).
            return f"Задание «{имя}» не выполнено: {НЕТ_СТРАНЫ_STEAM}"
        _отметить(род, "начато")
        тайны = secrets_store.загрузить()
        клиент_модели = api.Clients(тайны.deepseek_ключ)
        индекс = similar.Индекс()
        async with ss.клиент() as к, eshop.клиент() as кe, metacritic.клиент() as км:
            # eShop выключен или страна eShop не выбрана — поля eShop пусты (по умолчанию): ни
            # запроса к Nintendo и Metacritic, даже если ветвь заданий забудет спросить.
            поля_eshop = dict(
                витрина=lambda будущие, страница: eshop.витрина(кe, регион, будущие=будущие, страница=страница),
                игра_eshop=lambda объект: eshop.игра(кe, регион, объект),
                # Пара в Steam ищется поиском Steam — клиентом Steam, в магазине страны Steam.
                найти_в_steam=lambda игра: eshop.найти_в_steam(к, игра, страна_steam=страна),
                найти_в_eshop=lambda игра: eshop.найти_в_eshop(кe, регион, игра),
                отзывы_eshop=lambda игра: metacritic.отзывы(км, игра),
                цены_eshop=lambda номера: eshop.цены(кe, регион, номера),
            ) if регион is not None else {}
            магазин = Магазин(
                найти=lambda метка, будущие, страница: ss.найти_с_отзывами(
                    к, метка, будущие=будущие, страница=страница, страна=страна),
                игра=lambda номер: ss.игра(к, номер, с_отзывами=False, страна=страна),
                **поля_eshop,
            )
            учётка = None
            if тайны.steam_ключ and тайны.steamid:
                учётка = Учётка(
                    библиотека=lambda: steam_account.библиотека(к, тайны.steam_ключ, тайны.steamid),
                    список_желаемого=lambda: steam_account.список_желаемого(к, тайны.steamid, тайны.steam_ключ),
                )
            минимум = (
                (lambda номер: itad.минимум(к, тайны.itad_ключ, номер, страна=страна)) if тайны.itad_ключ else None
            )

            async def судья(игра: ss.Игра) -> judge.Вердикт:
                try:
                    # Векторы — отдельным потоком: служба Ollama грузит модель секундами, а цикл
                    # событий веба (задание из кнопки) не должен замирать.
                    похожие = similar.блок(await asyncio.to_thread(индекс.похожие, игра))
                except Exception:  # служба векторов не ответила — отбор без RAG, а не без отбора
                    похожие = ""
                return await judge.судить(клиент_модели, каталог, игра, похожие)

            if род == "month":
                итог = (await месяц(каталог, магазин, судья)).текст("месяц")
            elif род == "week":
                итог = (await неделя(каталог, магазин, судья, индекс)).текст("неделя")
            else:
                итог = await день(магазин, учётка, минимум)
            _отметить(род, "выполнено")
            return итог
    except УжеИдёт:
        raise
    except BaseException as exc:
        if not isinstance(exc, asyncio.CancelledError):
            # Прерванный запуск (отмена, убитый процесс) отметки сбоя не получает — его догонят.
            _отметить(род, "сбой")
        текст = secrets_store.скрыть(f"Задание «{имя}» упало: {type(exc).__name__}: {exc}", тайны)
        if isinstance(exc, asyncio.CancelledError):
            текст = f"Задание «{имя}» прервано: служба остановлена"
        try:
            с = games_db.открыть()
            try:
                games_db.в_ленту(с, "сбой", текст)
            finally:
                с.close()
        finally:
            await asyncio.shield(уведомить(текст))
        raise
    finally:
        if клиент_модели is not None:
            await клиент_модели.aclose()
        if замок is not None:
            замок.close()


def main(доводы: list[str]) -> int:
    if len(доводы) != 1 or доводы[0] not in РОДЫ:
        print("запуск: python jobs.py day|week|month", file=sys.stderr)
        return 2
    try:
        итог = asyncio.run(запустить(доводы[0], agent_env.данные()))
    except УжеИдёт as exc:
        # Задание из кнопки веба ещё идёт: служба не дублирует его и не считает это сбоем.
        в_ленту_итог(f"Задание по расписанию пропущено: {exc} (запущено кнопкой)")
        print(str(exc))
        return 0
    except Exception as exc:  # запись в ленте и уведомление уже сделаны
        print(f"сбой: {type(exc).__name__}", file=sys.stderr)
        return 1
    print(итог)
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
