async def _сверка(с) -> None:
    """Полгода с последней сверки — строка в ленте и уведомление; повторяется каждую неделю,
    пока человек не сверит вкус. Первый запуск только заводит отсчёт."""
    последняя = games_db.отметка(с, "последняя_сверка")
    if последняя is None:
        games_db.поставить_отметку(с, "последняя_сверка", _сегодня())
        return
    if date.today() - date.fromisoformat(последняя[:10]) < СВЕРКА:
        return
    текст = "Полгода без сверки вкуса: проверьте список любимых игр — не поменялось ли что-то?"
    games_db.в_ленту(с, "сверка", текст)
    await уведомить(текст)


async def _обновить_календарь(с, магазин: Магазин) -> None:
    """Дата уточнилась или перенесена — запись обновлена; игра вышла — уходит в предложения."""
    с_eshop = _ходить_в_eshop(с)
    for запись in games_db.календарь(с):
        if es.это_eshop(int(запись["номер"])) and not с_eshop:
            continue  # выключенный eShop — ни запроса к Nintendo; запись ждёт включения
        try:
            игра = await _сведения(с, магазин, int(запись["номер"]))
        except ss.ОшибкаМагазина:
            continue  # прежние сведения остаются; через месяц — новая попытка
        if игра is None:
            continue
        игра = _с_прежними_отзывами(с, игра)
        games_db.запомнить_игру(с, игра)
        if игра.вышла:
            games_db.убрать_из_календаря(с, игра.номер)
            games_db.предложить(с, игра.номер, запись.get("причина") or "вышла игра из календаря")


def документы_истории(с) -> list[similar.Документ]:
    """База знаний RAG: библиотека с часами, список Steam, плюсы, минусы с причинами, «уже
    играл». Игры без описания в хранилище идут одним именем — вектор беднее, но игра не пропадает."""
    отметки: dict[int, str] = {}
    имена: dict[int, str] = {}
    for з in games_db.библиотека(с):
        отметки[int(з["номер"])] = f"в библиотеке, {float(з.get('часы') or 0):.0f} ч"
        имена[int(з["номер"])] = з.get("имя") or ""
    for номер in games_db.список_steam(с):
        отметки.setdefault(номер, "в списке желаемого Steam")
    for з in games_db.предложения(с) + games_db.календарь(с):
        if з.get("оценка") is True:
            отметки[int(з["номер"])] = "плюс"
    for з in _оценённые_минусом(с):
        причина = з.get("причина_оценки") or ""
        отметки[int(з["номер"])] = f"минус: {причина}" if причина else "минус"
    for з in _сыгранные(с):
        отметки[int(з["номер"])] = "уже играл: " + ("понравилась" if з["понравилась"] else "не понравилась")
    документы = []
    for номер, отметка in отметки.items():
        запись = games_db.игра(с, номер)
        игра = _игра_из_записи(запись) if запись else ss.Игра(номер=номер, имя=имена.get(номер) or str(номер))
        документы.append(similar.Документ(номер, игра.имя, similar.текст_игры(игра), отметка))
    return документы


def _оценённые_минусом(с) -> list[dict]:
    return [dict(р) for р in с.execute(
        "SELECT номер, причина_оценки FROM suggestions WHERE оценка = 0"
    ).fetchall()]


def _сыгранные(с) -> list[dict]:
    return [dict(р) for р in с.execute("SELECT номер, понравилась FROM played").fetchall()]


async def неделя(
    каталог: Path, магазин: Магазин, судья: Судья, индекс: similar.Индекс | None = None
) -> Итог:
    """Предложения вышедших игр — раз в неделю. Перед отбором — пересборка RAG: судья видит
    отметки человека за неделю."""
    с = games_db.открыть()
    try:
        await _сверка(с)
        if индекс is not None:
            ход(с, "week", этап="пересобираю поиск похожих игр")
            try:
                await asyncio.to_thread(индекс.пересобрать, документы_истории(с))
            except Exception as exc:  # прежний индекс цел (`similar.Индекс.пересобрать`)
                _в_ленту(с, "сбой", f"RAG не пересобран: {exc}")
        итог = await _отобрать(
            каталог, с, магазин, судья, будущие=False, нужно=НУЖНО - games_db.открытых(с, без_eshop=not _ходить_в_eshop(с)),
        )
        games_db.в_ленту(с, "итог", итог.текст("Неделя, вышедшие игры"))
        return итог
    finally:
        с.close()


