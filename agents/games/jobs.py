async def _сведения(с, магазин: Магазин, номер: int) -> ss.Игра | None:
    """Сведения об игре из её магазина. Игру eShop каталог отдаёт по коду записи (`объект`), а
    не по nsuid: код берётся из хранилища; его нет — сведений нет."""
    if es.это_eshop(номер):
        запись = games_db.игра(с, номер)
        объект = (запись or {}).get("объект")
        return await магазин.игра_eshop(объект) if объект else None
    return await магазин.игра(номер)


