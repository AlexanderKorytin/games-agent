async def _синхронизировать(с, учётка: Учётка | None) -> None:
    """Библиотека и список желаемого Steam — порознь: закрытая библиотека не должна стоить
    синхронизации списка. Нет ключа или библиотека закрыта — одна строка в ленте, пока не
    исправится, а не уведомление каждый день."""
    if учётка is None:
        if not games_db.отметка(с, "нет_ключа_steam"):
            _в_ленту(с, "сбой", "Ключа Steam нет: библиотека и список желаемого Steam не читаются. Войдите в настройках.")
            games_db.поставить_отметку(с, "нет_ключа_steam", _сегодня())
        return
    import steam_account

    # Ключ есть — прежняя отметка «нет ключа» снимается: при новой потере ключа строка в ленте
    # снова появится.
    games_db.поставить_отметку(с, "нет_ключа_steam", "")
    try:
        games_db.обновить_библиотеку(с, await учётка.библиотека())
        games_db.поставить_отметку(с, "библиотека_закрыта", "")
    except steam_account.БиблиотекаЗакрыта as exc:
        if not games_db.отметка(с, "библиотека_закрыта"):
            _в_ленту(с, "сбой", str(exc))
            games_db.поставить_отметку(с, "библиотека_закрыта", _сегодня())
    except Exception as exc:  # noqa: BLE001
        текст = f"Библиотека Steam не прочитана: {exc}"
        _в_ленту(с, "сбой", текст)
        await уведомить(secrets_store.скрыть(текст, secrets_store.загрузить()))
    try:
        games_db.обновить_список_steam(с, await учётка.список_желаемого())
    except Exception as exc:  # noqa: BLE001
        _в_ленту(с, "сбой", f"Список желаемого Steam не прочитан: {exc}")


async def _скидки(с, магазин: Магазин, минимум: Минимум | None) -> list[str]:
    """Новые скидки на желаемое (своё и Steam): запись в ленте и уведомление на каждую. Сначала
    цены Steam по одной игре, затем цены eShop — одним запросом на все: свои игры eShop и пары
    игр Steam.

    Сбой одной игры не останавливает остальные: однодневная скидка на соседнюю игру дороже
    порядка. Сбои собираются одной строкой «сбой» в ленте."""
    новые: list[str] = []
    сбои: list[str] = []
    записи = games_db.желаемое(с)
    игры_steam: list[ss.Игра] = []
    for запись in записи:
        if es.это_eshop(int(запись["номер"])):
            continue  # цены eShop — одним запросом после цикла Steam
        try:
            игра = await магазин.игра(int(запись["номер"]))
        except ss.ОшибкаМагазина as exc:
            сбои.append(f"{запись.get('имя') or запись['номер']}: {exc}")
            continue
        if игра is None:
            continue
        # Сведения — до проверки цены: игра из списка Steam, которая ещё не продаётся, иначе
        # так и оставалась бы на вкладке «Желаемое» без названия (живой сценарий).
        игра = _с_прежними_отзывами(с, игра)
        games_db.запомнить_игру(с, игра)
        игры_steam.append(игра)
        if игра.цена is None:
            continue
        if игра.скидка <= 0:
            games_db.отметить_цену(с, игра.номер, игра.цена, игра.скидка, валюта=игра.валюта)
            continue
        текст = (
            f"Скидка {игра.скидка} % на «{игра.имя}» в Steam: {_сумма(игра.цена, игра.валюта)} "
            f"вместо {_сумма(игра.цена_без_скидки or игра.цена, игра.валюта)}"
        )
        if минимум is not None:
            текст += await _про_минимум(минимум, игра)
        # Отметка цены и строка ленты — одной транзакцией (`games_db.отметить_цену`).
        if games_db.отметить_цену(с, игра.номер, игра.цена, игра.скидка, текст, валюта=игра.валюта):
            await уведомить(текст)
            новые.append(текст)
    if _ходить_в_eshop(с):
        новые += await _скидки_eshop(с, магазин, записи, игры_steam, _Отказы(сбои))
    if сбои:
        текст = "Проверка скидок не дошла до игр: " + "; ".join(сбои)
        _в_ленту(с, "сбой", текст)
        await уведомить(текст)
    return новые


async def _скидки_eshop(
    с, магазин: Магазин, записи: list[dict], игры_steam: list[ss.Игра], отказы: _Отказы
) -> list[str]:
    """Цены eShop желаемого. Игра Steam без сверенной пары сперва ищется в eShop — один раз за
    всё время. Имя в уведомлении — имя плашки: у пары — имя Steam.

    Исторического минимума eShop у IsThereAnyDeal нет: минимум — свой, за время наблюдения
    (`games_db.минимум_наблюдений`), и берётся ДО записи новой цены, иначе новая цена сравнивалась
    бы сама с собой."""
    for игра in игры_steam:
        await _связать_с_eshop(с, магазин, игра, отказы)
    имена: dict[int, str] = {}
    for игра in игры_steam:
        if (пара := games_db.пара(с, игра.номер)) is not None:
            имена[пара] = игра.имя
    for запись in записи:
        номер = int(запись["номер"])
        if es.это_eshop(номер):
            имена.setdefault(номер, запись.get("имя") or str(номер))
    if not имена:
        return []
    try:
        цены = await магазин.цены_eshop(list(имена))
    except ss.ОшибкаМагазина as exc:
        отказы.отметить("цены", f"eShop не ответил: {exc}")
        return []
    новые: list[str] = []
    for номер, имя in имена.items():
        ц = цены.get(номер)
        if ц is None:
            continue
        прежний_минимум = games_db.минимум_наблюдений(с, номер)
        games_db.обновить_цену(
            с, номер, цена=ц.цена, цена_без_скидки=ц.цена_без_скидки, скидка=ц.скидка,
            валюта=ц.валюта, скидка_до=ц.до,
        )
        if ц.скидка <= 0:
            games_db.отметить_цену(с, номер, ц.цена, ц.скидка, валюта=ц.валюта)
            continue
        текст = (
            f"Скидка {ц.скидка} % на «{имя}» в eShop: {_сумма(ц.цена, ц.валюта)} "
            f"вместо {_сумма(ц.цена_без_скидки, ц.валюта)}"
        )
        try:
            текст += f", до {_дата_словами(ц.до)}" if ц.до else ""
        except ValueError:
            pass  # срок не разобран — скидка дороже срока
        текст += _про_минимум_наблюдений(прежний_минимум, ц)
        if games_db.отметить_цену(с, номер, ц.цена, ц.скидка, текст, валюта=ц.валюта):
            await уведомить(текст)
            новые.append(текст)
    return новые


def _про_минимум_наблюдений(м: dict | None, ц: es.Цена) -> str:
    """Свой минимум; цену ещё не отмечали либо отмечали в другой валюте — сравнивать не с чем."""
    if м is None or м["валюта"] != ц.валюта:
        return ""
    if ц.цена <= м["цена"]:
        return "; это минимум за время наблюдения"
    когда = datetime.fromisoformat(м["когда"])
    # Отметка — по UTC: вечерняя отметка по местному времени — уже другой день.
    день = когда.astimezone().date() if когда.tzinfo else когда.date()
    return f"; минимум за время наблюдения — {_сумма(м['цена'], м['валюта'])} ({_дата_словами(день.isoformat())})"


_МЕСЯЦЫ = ("января", "февраля", "марта", "апреля", "мая", "июня", "июля", "августа",
           "сентября", "октября", "ноября", "декабря")


def _дата_словами(когда: str) -> str:
    """«2026-11-05» → «5 ноября»; год — только если он не текущий. Принимает и полную отметку
    времени: берётся дата."""
    день = date.fromisoformat(когда[:10])
    текст = f"{день.day} {_МЕСЯЦЫ[день.month - 1]}"
    return текст if день.year == date.fromisoformat(_сегодня()).year else f"{текст} {день.year}"


async def _про_минимум(минимум: Минимум, игра: ss.Игра) -> str:
    try:
        м = await минимум(игра.номер)
    except Exception as exc:  # минимум — довод, а не повод терять скидку
        return f"; исторический минимум не узнал: {exc}"
    if м is None:
        return ""
    когда = str(getattr(м, "когда", ""))[:10]
    if not игра.валюта or getattr(м, "валюта", "") != игра.валюта:
        return ""  # минимум в другой валюте (или валюта цены не известна) с ценой не сравнить
    if игра.цена is not None and игра.цена <= м.цена:
        return "; это исторический минимум"
    return f"; минимум был {_сумма(м.цена, м.валюта)} ({когда})"


def _сегодня() -> str:
    return date.today().isoformat()


async def _выходы(с) -> None:
    """Игра календаря выходит сегодня — одно уведомление."""
    for запись in games_db.календарь(с):
        if запись.get("дата") != _сегодня():
            continue
        ключ = f"выход_сообщён:{запись['номер']}"
        if games_db.отметка(с, ключ) is not None:
            continue
        текст = f"Сегодня выходит «{запись.get('имя') or запись['номер']}»"
        games_db.в_ленту(с, "выход", текст)
        games_db.поставить_отметку(с, ключ, _сегодня())
        await уведомить(текст)


async def день(
    магазин: Магазин, учётка: Учётка | None = None, минимум: Минимум | None = None,
) -> str:
    """Синхронизация, скидки и выходы игр — каждый день: однодневная скидка и день выхода ждать
    недели не могут. Подбора игр здесь нет — он в задании недели."""
    с = games_db.открыть()
    try:
        ход(с, "day", этап="синхронизирую библиотеку и список желаемого Steam")
        await _синхронизировать(с, учётка)
        if минимум is None and games_db.отметка(с, "нет_ключа_itad") is None:
            _в_ленту(с, "итог", "Ключа IsThereAnyDeal нет: уведомления о скидке идут без исторического минимума цены.")
            games_db.поставить_отметку(с, "нет_ключа_itad", _сегодня())
        # Скидки — до отбора и отдельно: сбой отбора не должен стоить человеку скидки.
        ход(с, "day", этап="проверяю скидки на желаемое")
        скидок = 0
        try:
            скидок = len(await _скидки(с, магазин, минимум))
        except Exception as exc:
            текст = f"Проверка скидок упала: {type(exc).__name__}: {exc}"
            _в_ленту(с, "сбой", текст)
            await уведомить(текст)
        await _выходы(с)
        итог = f"День: библиотека и желаемое сверены, новых скидок {скидок}"
        games_db.в_ленту(с, "итог", итог)
        return итог
    finally:
        с.close()


