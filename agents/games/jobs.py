# Будущая игра без даты в выдаче вышедших перепроверяется не чаще раза в неделю: иначе она
# держала бы страницу, а навсегда отсеять её нельзя — она однажды выйдет (повторный просмотр).
ПЕРЕПРОВЕРКА = timedelta(days=7)


def _негодна_заранее(с, номер: int, будущие: bool) -> bool:
    """Игра заведомо не годна для этого задания по уже известным сведениям хранилища: не игра;
    в выдаче вышедших — ещё не вышла и её дата не наступила; в выдаче будущих — уже вышла. Без этого
    негодная игра держала бы страницу «непустой», и до следующей страницы задание не доходило бы
    никогда (находка просмотра шва 12–17)."""
    запись = games_db.игра(с, номер)
    if запись is None:
        return False
    if будущие:
        return bool(запись.get("вышла"))
    if запись.get("вышла") is False:
        дата = запись.get("дата")
        if дата is not None:
            return дата > _сегодня()
        обновлено = str(запись.get("обновлено") or "")[:10]
        return bool(обновлено) and date.fromisoformat(обновлено) > date.today() - ПЕРЕПРОВЕРКА
    return False


async def _страница_с_кандидатами(
    с, магазин: Магазин, метка: int, будущие: bool, исключить: set[int]
) -> list[tuple[int, ss.Отзывы]]:
    """Первая страница метки, где есть годные кандидаты. Поиск без суда и без сведений об играх
    — дёшево; кончилась выдача — пусто."""
    страница = 0
    while True:
        пары = await магазин.найти(метка, будущие, страница)
        if not пары:
            return []
        годные = [(н, о) for н, о in пары if н not in исключить and not _негодна_заранее(с, н, будущие)]
        if годные:
            return годные
        страница += 1


def _регион_eshop(с) -> eshop.Регион | None:
    """Регион eShop человека: eShop включён, страна выбрана и в ней eShop поддержан. Иначе `None`."""
    if not games_db.eshop_включён(с):
        return None
    страна = games_db.страна_eshop(с)
    return eshop.регион(страна) if страна else None


def _ходить_в_eshop(с) -> bool:
    """Одна точка входа всех ветвей eShop заданий: источника отбора, привязки пары и цен.
    Выключатель человека (`games_db.eshop_включён`) и страна eShop проверяются здесь."""
    return _регион_eshop(с) is not None


def _по_очереди(источники: list[list[tuple[int, ss.Отзывы]]]) -> dict[int, ss.Отзывы]:
    """Кандидаты источников по кругу, по одному из каждого; повтор номера пропускается. Иначе
    игры без оценки (будущие) шли бы сплошь из первой метки Steam, а eShop не доходил бы до суда
    никогда: нужно 10 всего, а не по 10 на источник."""
    запас: dict[int, ss.Отзывы] = {}
    for ряд in zip_longest(*источники):
        for пара in ряд:
            if пара is not None:
                запас.setdefault(*пара)
    return запас


@dataclass
class _Отказы:
    """Службы, отказавшие в этом запуске. После первого отказа служба до конца запуска не
    зовётся: у `_запрос` повторы — минуты на один отказ, и 50 записей страницы держали бы замок
    задания часами. В `тексты` — одна строка на службу."""

    тексты: list[str]
    отказали: set[str] = field(default_factory=set)

    def отметить(self, служба: str, текст: str) -> None:
        if служба not in self.отказали:
            self.отказали.add(служба)
            self.тексты.append(текст)


async def _страница_eshop(
    с, магазин: Магазин, будущие: bool, исключить: set[int], отказы: _Отказы,
    запреты_имён: set[str] = frozenset(),
) -> list[tuple[int, ss.Отзывы]]:
    """Первая страница витрины eShop, где есть годные кандидаты, — только игры БЕЗ пары в Steam:
    игра с парой приходит поиском Steam и получает цену eShop привязкой (`_связать_с_eshop`).

    Каждая годная запись ложится в хранилище: код каталога нужен `_сведения`, цена — плашке пары.
    Пара ищется один раз за всё время (`pairs`). Поиск пары отказал — несверенные записи ждут
    следующего запуска (в `pairs` не пишутся), страница дальше не листается. Оценка вышедшей игры
    без пары — оценка игроков Metacritic; отказал Metacritic — оценка прежняя. У будущих игр
    оценки нет, запроса нет. Сбой самой витрины — наверх: решает `_отобрать`.

    Запись, чьё сравнимое имя запрещено человеком (`taste.запреты_по_имени`), пропускается, как
    исключённый номер: запрет переживает смену зоны eShop, где у игры другой номер."""
    страница = 0
    while True:
        игры = await магазин.витрина(будущие, страница)
        if not игры:
            return []
        годные: list[tuple[int, ss.Отзывы]] = []
        for игра in игры:
            номер = игра.номер
            if номер in исключить or _негодна_заранее(с, номер, будущие):
                continue
            if запреты_имён and es.сравнимое(игра.имя) in запреты_имён:
                continue
            if games_db.пара_сверена(с, номер):
                пара = games_db.пара(с, номер)
            elif "пара_steam" in отказы.отказали:
                continue
            else:
                try:
                    пара = await магазин.найти_в_steam(игра)
                except ss.ОшибкаМагазина as exc:
                    отказы.отметить("пара_steam", f"поиск пары не удался: {игра.имя}: {exc}")
                    games_db.запомнить_игру(с, _с_прежними_отзывами(с, игра))
                    continue
                games_db.записать_пару(с, номер, пара)
            игра = _с_прежними_отзывами(с, игра)
            if пара is None and not будущие and "metacritic" not in отказы.отказали:
                try:
                    оценка = await магазин.отзывы_eshop(игра)
                except ss.ОшибкаМагазина as exc:
                    # Оценки нет — кандидат остаётся с прежней: отбор без неё лучше пропуска.
                    отказы.отметить("metacritic", f"оценка Metacritic не получена: {игра.имя}: {exc}")
                else:
                    if оценка.всего > 0:
                        игра = replace(игра, отзывы=оценка)
            games_db.запомнить_игру(с, игра)
            if пара is None:
                годные.append((номер, игра.отзывы))
        if годные or "пара_steam" in отказы.отказали:
            return годные
        страница += 1


async def _отобрать(
    каталог: Path, с, магазин: Магазин, судья: Судья, *, будущие: bool, нужно: int
) -> Итог:
    итог = Итог(нужно=нужно)
    критерии, итог.жалобы_критериев = taste.критерии(каталог)
    if not критерии:
        raise RuntimeError("в карточке нет «Критериев»: опрос вкуса не пройден")
    if нужно <= 0:
        return итог
    отпечаток = taste.отпечаток(каталог)
    # Решения человека и уже показанное; они же занимают пару (`_пара_занята`).
    решено = games_db.показанные(с) | games_db.куплены(с) | taste.запреты(каталог)
    исключить = решено | games_db.отказано(с, отпечаток) | games_db.отказано(с, НЕ_ИГРА)

    род = "month" if будущие else "week"
    ход(с, род, этап="ищу кандидатов по вашим критериям", нужно=нужно)
    источники = [
        await _страница_с_кандидатами(с, магазин, критерий.метка, будущие, исключить)
        for критерий in sorted(критерии, key=lambda к: -к.вес)
    ]
    отказы = _Отказы(итог.сбои_eshop)
    с_eshop = _ходить_в_eshop(с)
    if с_eshop:
        try:
            источники.append(await _страница_eshop(
                с, магазин, будущие, исключить, отказы, taste.запреты_по_имени(каталог)))
        except ss.ОшибкаМагазина as exc:
            # eShop лёг — не повод терять Steam: источник пуст, причина в итоге.
            итог.сбои_eshop.append(f"eShop не ответил: {exc}")
    запас = _по_очереди(источники)
    итог.кандидатов = len(запас)

    # Лучшие по оценке (SteamDB из сводки выдачи Steam, игроки Metacritic у eShop) — первыми; без
    # отзывов — в конце, в порядке очереди источников: сортировка устойчивая. Сведения об игре —
    # только перед судом: до нужного числа доходит малая часть.
    порядок = sorted(запас, key=lambda н: -(ss.оценка(запас[н]) if ss.оценка(запас[н]) is not None else -1.0))
    принятые: set[int] = set()
    for номер in порядок:
        if len(итог.подошло) >= нужно:
            break
        # Выключенный eShop — пары не в счёт: скрытая версия eShop не блокирует версию Steam.
        if с_eshop and _пара_занята(с, номер, решено | принятые):
            continue
        try:
            игра = await _сведения(с, магазин, номер)
        except ss.ОшибкаМагазина as exc:
            # Одна игра не отдана — не повод терять остальные; число видно в итоге.
            итог.сбои_магазина.append(f"{номер}: {exc}")
            continue
        if игра is None or игра.род != "game":
            games_db.запомнить_отказ(с, номер, НЕ_ИГРА)
            continue
        игра = _с_прежними_отзывами(с, игра, запас[номер])
        games_db.запомнить_игру(с, игра)
        # Выдача могла устареть: вышедшая игра в будущих не нужна, и наоборот. Сведения уже в
        # хранилище — `_негодна_заранее` отсеет её до следующего запуска.
        if игра.вышла == будущие:
            continue
        итог.судимо += 1
        ход(с, род, этап="сужу игры", нужно=нужно, подошло=len(итог.подошло), проверено=итог.судимо, кандидатов=итог.кандидатов)
        try:
            вердикт = await судья(игра)
        except ValueError as exc:
            итог.ошибки_разбора.append(f"{игра.имя}: {exc}")
            continue
        if not вердикт.подходит:
            games_db.запомнить_отказ(с, игра.номер, отпечаток)
            continue
        if с_eshop:
            await _связать_с_eshop(с, магазин, игра, отказы)
            if _пара_занята(с, игра.номер, решено | принятые):
                continue
        записано = (
            games_db.в_календарь(с, игра.номер, вердикт.причина)
            if будущие
            else games_db.предложить(с, игра.номер, вердикт.причина)
        )
        if записано:
            итог.подошло.append(игра.имя)
            принятые.add(игра.номер)
    return итог


def _пара_занята(с, номер: int, занятые: set[int]) -> bool:
    """Вторая плашка той же игры не нужна. Кандидат eShop с парой (её нашла игра Steam этого
    запуска) — уже пришёл через Steam. Игра Steam, чья пара запрещена, показана, куплена или
    подошла в этом запуске, — не предлагается: иначе «Нет» на версии eShop обходилось бы.
    Пару занимают только решения человека: отказ модели о другой версии и «не игра» (пропавшая
    запись каталога) одобренную версию Steam не снимают."""
    пара = games_db.пара(с, номер)
    if пара is None:
        return False
    return es.это_eshop(номер) or пара in занятые


async def _связать_с_eshop(с, магазин: Магазин, игра: ss.Игра, отказы: _Отказы) -> None:
    """Та же игра Steam в eShop: плашка игры Steam показывает и цену eShop. Ищется один раз за
    всё время (`pairs`): не нашлось — тоже ответ. Сбой поиска — строка в `отказы`, до конца
    запуска поиск не зовётся; предложение не отменяется, следующий запуск поищет снова."""
    if (es.это_eshop(игра.номер) or games_db.пара_сверена(с, игра.номер)
            or "пара_eshop" in отказы.отказали):
        return
    try:
        найдена = await магазин.найти_в_eshop(игра)
    except ss.ОшибкаМагазина as exc:
        отказы.отметить("пара_eshop", f"поиск пары не удался: {игра.имя}: {exc}")
        return
    if найдена is not None:
        games_db.запомнить_игру(с, _с_прежними_отзывами(с, найдена))
    games_db.записать_пару(с, игра.номер, найдена.номер if найдена else None)


