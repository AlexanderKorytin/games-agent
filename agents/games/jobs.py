@dataclass
class Итог:
    нужно: int = 0
    кандидатов: int = 0
    судимо: int = 0
    подошло: list[str] = field(default_factory=list)
    ошибки_разбора: list[str] = field(default_factory=list)
    сбои_магазина: list[str] = field(default_factory=list)
    # Сбои поиска пары и оценки Metacritic: игры не потеряны, строки — как есть.
    сбои_eshop: list[str] = field(default_factory=list)
    жалобы_критериев: list[str] = field(default_factory=list)

    def текст(self, имя: str) -> str:
        if self.нужно <= 0:
            return f"{имя}: открытых предложений уже {НУЖНО}, новых не искал"
        части = [
            f"{имя}: нужно {self.нужно}, кандидатов {self.кандидатов}, судимо {self.судимо}, "
            f"подошло {len(self.подошло)}"
        ]
        if self.подошло:
            части.append("подошли: " + ", ".join(self.подошло))
        if self.ошибки_разбора:
            части.append(f"ответ модели не разобран {len(self.ошибки_разбора)} раз: {self.ошибки_разбора[0]}")
        if self.сбои_магазина:
            части.append(f"магазин не отдал {len(self.сбои_магазина)} игр: {self.сбои_магазина[0]}")
        if self.сбои_eshop:
            части.append("; ".join(self.сбои_eshop))
        if self.жалобы_критериев:
            части.append("строки «Критериев» не того вида пропущены: " + "; ".join(self.жалобы_критериев))
        return ". ".join(части)


